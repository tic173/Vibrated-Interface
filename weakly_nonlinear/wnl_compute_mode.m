function [correction,information] = ...
        solve_eigenpair_correction(block,direct,spec,phaseRow, ...
        phaseTarget,opts,solverChoice,initialCorrection)
% Solve [A B*phi; c' 0]*[dphi;dlambda]=[-A*phi;1-c'*phi].
if ~ismember(solverChoice,{'gmres','lsqr'})
    error('wnl_compute_mode:EigenpairCorrectionSolver', ...
        'solverChoice must be gmres or lsqr.');
end
numberOfUnknowns = numel(direct);
bordered = [block.A,sparse(block.Bslow*direct); ...
    sparse(phaseRow),sparse(1,1)];
phaseDefect = phaseTarget-phaseRow*direct;
rhs = [-block.A*direct;phaseDefect];
[rowScaledMatrix,scaledRhs] = equilibrate_equations(bordered,rhs);
[scaledMatrix,columnScale] = equilibrate_columns(rowScaledMatrix);
scaledCorrection = complex(zeros(numberOfUnknowns+1,1));
physicalCorrectionGuess = complex(zeros(numberOfUnknowns+1,1));
if ~isempty(initialCorrection)
    if numel(initialCorrection) ~= numberOfUnknowns+1
        error('wnl_compute_mode:EigenpairWarmStartSize', ...
            'The correction warm start has the wrong number of entries.');
    end
    initialCorrection = initialCorrection(:);
    if all(isfinite(real(initialCorrection))) && ...
            all(isfinite(imag(initialCorrection)))
        scaledCorrection = initialCorrection./columnScale;
        physicalCorrectionGuess = initialCorrection;
    end
end
bestPhysicalCorrection = [];
bestEquationResidual = Inf;
bestFlag = NaN;
bestSolver = 'unavailable';
totalIterations = 0;
gmresInformation = struct('attempted',false,'accepted',false);

numberOfHarmonics = numel(spec.n);
canUseBlockGmres = opts.eigenpairUseBlockGmres && ...
    numberOfHarmonics > 1 && ...
    spec.ndof*numberOfHarmonics == numberOfUnknowns;
if strcmp(solverChoice,'gmres') && canUseBlockGmres
    gmresInformation.attempted = true;
    try
        [blockFactors,blockRegularization,blockInverseGain] = ...
            factor_temporal_diagonal_blocks(scaledMatrix,spec.ndof, ...
            numberOfHarmonics,opts);
        [bottomBorder,borderResponse,borderSchur] = ...
            factor_bordered_block_jacobi(scaledMatrix,blockFactors, ...
            spec.ndof,numberOfHarmonics);
        preconditioner = @(rightHandSideValue) ...
            apply_bordered_block_jacobi_inverse(rightHandSideValue, ...
            blockFactors,spec.ndof,numberOfHarmonics,bottomBorder, ...
            borderResponse,borderSchur);
        [gmresCandidate,gmresFlag,gmresRelativeResidual, ...
            gmresIteration,gmresResidualHistory] = gmres( ...
            scaledMatrix,scaledRhs,opts.eigenpairGmresRestart, ...
            opts.eigenpairRefinementSolveTolerance, ...
            opts.eigenpairGmresMaxCycles,preconditioner,[], ...
            scaledCorrection);
        gmresIterations = gmres_iteration_count( ...
            gmresIteration,opts.eigenpairGmresRestart);
        totalIterations = totalIterations+gmresIterations;
        gmresEquationResidual = norm( ...
            scaledMatrix*gmresCandidate-scaledRhs) / ...
            max(norm(scaledRhs),eps);
        finiteGmres = all(isfinite(real(gmresCandidate))) && ...
            all(isfinite(imag(gmresCandidate)));
        if finiteGmres
            bestPhysicalCorrection = columnScale.*gmresCandidate;
            bestEquationResidual = gmresEquationResidual;
            bestFlag = gmresFlag;
            bestSolver = 'block-GMRES';
        end
        gmresInformation.flag = gmresFlag;
        gmresInformation.relativeResidual = gmresRelativeResidual;
        gmresInformation.equationResidual = gmresEquationResidual;
        gmresInformation.iteration = gmresIteration;
        gmresInformation.iterations = gmresIterations;
        gmresInformation.residualHistory = gmresResidualHistory;
        gmresInformation.blockRegularization = blockRegularization;
        gmresInformation.blockInverseGain = blockInverseGain;
        gmresInformation.borderSchurComplement = borderSchur;
        gmresInformation.accepted = finiteGmres && ...
            gmresEquationResidual <= ...
            opts.eigenpairGmresAcceptanceTolerance;
    catch gmresError
        gmresInformation.errorIdentifier = gmresError.identifier;
        gmresInformation.errorMessage = gmresError.message;
    end
end

lsqrInformation = struct('attempted',false);
if strcmp(solverChoice,'lsqr') && ...
        opts.eigenpairLsqrFallbackMaxIterations > 0
    % Add the physical correction norm to the least-squares objective before
    % column equilibration:
    %
    %   min_delta ||R(K*delta-rhs)||^2 + alpha||delta_q||^2.
    %
    % Column scaling of this complete objective improves conditioning but
    % does not change the physical Tikhonov norm. This avoids both extremes
    % seen in earlier releases: a fast scaled solve with an enormous pressure
    % component and an unscaled physical LSQR solve whose bordered residual
    % remained O(1) after hundreds of iterations.
    lsqrInformation.attempted = true;
    correctionRegularization = ...
        opts.eigenpairCorrectionRegularization;
    if correctionRegularization > 0
        regularizationRows = [ ...
            sqrt(correctionRegularization)*speye(numberOfUnknowns), ...
            sparse(numberOfUnknowns,1)];
        lsqrObjectiveMatrix = [rowScaledMatrix;regularizationRows];
        lsqrObjectiveRhs = [scaledRhs; ...
            complex(zeros(numberOfUnknowns,1))];
        [lsqrMatrix,lsqrColumnScale] = ...
            equilibrate_columns(lsqrObjectiveMatrix);
    else
        lsqrMatrix = rowScaledMatrix;
        lsqrObjectiveRhs = scaledRhs;
        lsqrColumnScale = ones(numberOfUnknowns+1,1);
    end
    scaledLsqrGuess = physicalCorrectionGuess./lsqrColumnScale;
    for fallbackAttempt = 0:opts.eigenpairLsqrFallbackMaxRestarts
        [lsqrCandidate,lsqrFlag,lsqrRelativeResidual,iterations] = ...
            lsqr(lsqrMatrix,lsqrObjectiveRhs, ...
            opts.eigenpairRefinementSolveTolerance, ...
            opts.eigenpairLsqrFallbackMaxIterations,[],[], ...
            scaledLsqrGuess);
        totalIterations = totalIterations+iterations;
        physicalLsqrCandidate = lsqrColumnScale.*lsqrCandidate;
        lsqrEquationResidual = norm( ...
            rowScaledMatrix*physicalLsqrCandidate-scaledRhs) / ...
            max(norm(scaledRhs),eps);
        lsqrAugmentedResidual = norm( ...
            lsqrMatrix*lsqrCandidate-lsqrObjectiveRhs) / ...
            max(norm(lsqrObjectiveRhs),eps);
        finiteLsqr = all(isfinite(real(lsqrCandidate))) && ...
            all(isfinite(imag(lsqrCandidate)));
        if finiteLsqr && lsqrEquationResidual < bestEquationResidual
            bestPhysicalCorrection = physicalLsqrCandidate;
            bestEquationResidual = lsqrEquationResidual;
            bestFlag = lsqrFlag;
            bestSolver = 'regularized LSQR fallback';
        end
        physicalCorrectionGuess = physicalLsqrCandidate;
        scaledLsqrGuess = lsqrCandidate;
        lsqrInformation.flag = lsqrFlag;
        lsqrInformation.relativeResidual = lsqrRelativeResidual;
        lsqrInformation.equationResidual = lsqrEquationResidual;
        lsqrInformation.augmentedResidual = lsqrAugmentedResidual;
        lsqrInformation.iterations = iterations;
        lsqrInformation.attempts = fallbackAttempt+1;
        lsqrInformation.regularization = correctionRegularization;
        lsqrInformation.columnScaleRange = ...
            positive_range(lsqrColumnScale);
        if lsqrFlag == 0 || lsqrEquationResidual <= ...
                opts.eigenpairCorrectionEquationTolerance
            break;
        end
    end
end

available = ~isempty(bestPhysicalCorrection) && ...
    all(isfinite(real(bestPhysicalCorrection))) && ...
    all(isfinite(imag(bestPhysicalCorrection)));
if available
    correction = bestPhysicalCorrection;
    % Iterative least-squares convergence is dominated by the many physical
    % rows, so a small reported global residual may still contain an O(1)
    % error in the single phase/scale row. Enforce that row algebraically.
    scaleDirection = direct;
    scaleDenominator = phaseRow*scaleDirection;
    if abs(scaleDenominator) <= eps
        available = false;
        correction = complex(zeros(numberOfUnknowns+1,1));
    else
        correction(1:numberOfUnknowns) = ...
            correction(1:numberOfUnknowns) + scaleDirection * ...
            ((phaseDefect-phaseRow*correction(1:numberOfUnknowns)) / ...
            scaleDenominator);
    end
else
    correction = complex(zeros(numberOfUnknowns+1,1));
end
trialAvailable = available;
if trialAvailable
    physicalCorrectionResidual = bordered*correction-rhs;
    phaseConstraintResidual = abs(physicalCorrectionResidual(end));
    topEquationResidual = norm( ...
        physicalCorrectionResidual(1:numberOfUnknowns)) / ...
        max(norm(rhs(1:numberOfUnknowns)),eps);
    available = isfinite(topEquationResidual) && ...
        isfinite(phaseConstraintResidual) && ...
        topEquationResidual <= ...
            opts.eigenpairCorrectionEquationTolerance && ...
        phaseConstraintResidual <= ...
            opts.eigenpairCorrectionConstraintTolerance;
else
    topEquationResidual = Inf;
    phaseConstraintResidual = Inf;
end
information = struct('available',available,'solver',bestSolver, ...
    'trialAvailable',trialAvailable, ...
    'flag',bestFlag,'equationResidual',topEquationResidual, ...
    'scaledEquationResidual',bestEquationResidual, ...
    'phaseConstraintResidual',phaseConstraintResidual, ...
    'iterations',totalIterations,'gmres',gmresInformation, ...
    'lsqr',lsqrInformation);
if ~available && isfinite(topEquationResidual) && ...
        topEquationResidual > opts.eigenpairCorrectionEquationTolerance
    information.rejectionReason = sprintf([ ...
        'bordered equation residual %.3e exceeds tolerance %.3e'], ...
        topEquationResidual,opts.eigenpairCorrectionEquationTolerance);
else
    information.rejectionReason = '';
end
end

