function mode = wnl_compute_mode(model, spec, userOpts)
%WNL_COMPUTE_MODE Compute and normalize a direct/left Floquet null pair.
%
% Required model callback:
%   block = model.block(spec)
%
% Required block fields:
%   block.A      complete square Floquet matrix
%   block.Bslow  descriptor matrix multiplying the physical slow derivative
%
% The algebraic left vector y satisfies y'*A=0 and is normalized so that
% y'*Bslow*phi=1. It already contains any discrete adjoint weights needed
% for solvability; use y'*forcing for projections.

if nargin < 3
    userOpts = struct();
end
opts = wnl_options(userOpts);
modeWallClock = tic;
directWallClock = tic;
block = model.block(spec);
validate_block(block, spec);
tracking = struct();
tracking.used = false;
tracking.recoveryCacheUsed = isfield(spec,'recoveryCacheFile') && ...
    ~isempty(spec.recoveryCacheFile);
if tracking.recoveryCacheUsed
    tracking.recoveryCacheFile = spec.recoveryCacheFile;
else
    tracking.recoveryCacheFile = '';
end
directSingularValue = NaN;
leftSingularValue = NaN;

if ~isempty(opts.direct)
    direct = opts.direct(:);
elseif isfield(spec, 'direct') && ~isempty(spec.direct)
    direct = spec.direct(:);
elseif isfield(spec, 'directSeed') && ~isempty(spec.directSeed)
    if isfield(spec, 'prescribedDofs') && ...
            ~isempty(spec.prescribedDofs)
        [direct, directSingularValue, tracking.direct] = ...
            reconstruct_from_prescribed_dofs(block, ...
            spec.directSeed(:), spec, opts);
    else
        [direct, directSingularValue, tracking.direct] = ...
            tracked_constrained_null(block, ...
            spec.directSeed(:), opts);
    end
    tracking.used = true;
    if opts.verbose
        fprintf(['WNL direct reconstruction (%s, %s): effective sigma ', ...
            '= %.3e, scaled residual = %.3e, selected attempt = ', ...
            '%d/%d, LSQR flag = %d, total iterations = %d, ', ...
            'restarts = %d\n'], ...
            spec.label, tracking.direct.method, ...
            directSingularValue, ...
            tracking.direct.scaledResidual, ...
            tracking.direct.selectedAttempt, ...
            tracking.direct.numberOfAttempts, ...
            tracking.direct.flag, ...
            tracking.direct.iterations, tracking.direct.restarts);
    end
else
    [~, directSingularValue, direct] = smallest_svd(block.A, opts);
    if opts.verbose
        fprintf('WNL direct null solve (%s): sigma_min = %.3e\n', ...
            spec.label, directSingularValue);
    end
end
directSolveSeconds = toc(directWallClock);

if numel(direct) ~= size(block.A, 2)
    error('wnl_compute_mode:DirectSize', ...
        'Direct vector has %d entries; block requires %d.', ...
        numel(direct), size(block.A, 2));
end

if ~isempty(opts.normalizeDirect)
    trialField = wnl_make_field(spec, direct);
    normalized = opts.normalizeDirect(trialField);
    if isstruct(normalized)
        direct = wnl_field_vector(normalized);
    else
        direct = normalized(:);
    end
end

% The reduced interface Schur complement and the full primitive-variable
% discretization need not have exactly the same Floquet exponent.  At an
% operating point, refine both the full state and lambda before constructing
% the adjoint or nonlinear forcing.  Holding every interface coefficient
% fixed leaves an O(1e-6) residual floor that can be strongly amplified by
% the second-order light-fluid Stokes solve.
tracking.eigenpairRefinement = struct('attempted',false);
eigenpairRefinementSeconds = 0;
if tracking.used && opts.refineOperatingPointEigenpair && ...
        abs(wnl_spec_lambda(spec)) > 1.0e-13
    validateattributes(opts.coefficientModeResidualTolerance,{'numeric'}, ...
        {'scalar','real','positive','finite'});
    validateattributes( ...
        opts.eigenpairEscalationMaximumResidualRatio,{'numeric'}, ...
        {'scalar','real','>=',1,'finite'});
    validateattributes(opts.eigenpairEscalationMaxSteps,{'numeric'}, ...
        {'scalar','integer','positive'});
    eigenpairWallClock = tic;
    firstPassOpts = opts;
    if opts.autoEscalateEigenpairRefinement
        firstPassOpts.eigenpairRefinementMaxSteps = min( ...
            opts.eigenpairRefinementMaxSteps, ...
            opts.eigenpairEscalationMaxSteps);
    end
    [spec, block, direct, firstRefinement] = ...
        refine_operating_point_eigenpair(model,spec,block,direct, ...
        firstPassOpts);
    firstRefinement.escalated = false;
    firstRefinement.numberOfPasses = 1;
    firstRefinement.directResidualReady = ...
        firstRefinement.finalResidual <= ...
        opts.coefficientModeResidualTolerance;
    tracking.eigenpairRefinement = firstRefinement;
    remainingEscalationSteps = max(0, ...
        opts.eigenpairEscalationMaxSteps-firstRefinement.steps);
    if opts.autoEscalateEigenpairRefinement && ...
            ~firstRefinement.directResidualReady && ...
            ~firstRefinement.stoppedForReferenceMismatch && ...
            strcmp(firstRefinement.stopReason, ...
                'Newton-step budget exhausted') && ...
            remainingEscalationSteps > 0 && ...
            firstRefinement.finalResidual < ...
                firstRefinement.initialResidual && ...
            firstRefinement.finalResidual <= ...
                opts.eigenpairEscalationMaximumResidualRatio * ...
                opts.coefficientModeResidualTolerance
        escalationOpts = opts;
        escalationOpts.eigenpairRefinementMaxSteps = ...
            remainingEscalationSteps;
        escalationOpts.eigenpairReferenceLambda = ...
            firstRefinement.initialLambda;
        escalationOpts.eigenpairPriorAcceptedSteps = ...
            firstRefinement.steps;
        if opts.verbose
            fprintf(['WNL automatic eigenpair continuation (%s): ', ...
                'first-pass residual %.3e; continuing from the best ', ...
                'state with %d remaining Newton step(s) in the total ', ...
                '%d-step budget.\n'], ...
                spec.label,firstRefinement.finalResidual, ...
                remainingEscalationSteps, ...
                opts.eigenpairEscalationMaxSteps);
        end
        [spec,block,direct,escalationRefinement] = ...
            refine_operating_point_eigenpair(model,spec,block,direct, ...
            escalationOpts);
        tracking.eigenpairRefinement = combine_refinement_passes( ...
            firstRefinement,escalationRefinement,opts);
    end
    if ~isempty(opts.normalizeDirect)
        normalized = opts.normalizeDirect(wnl_make_field(spec,direct));
        if isstruct(normalized)
            direct = wnl_field_vector(normalized);
        else
            direct = normalized(:);
        end
    end
    if opts.verbose
        refinement = tracking.eigenpairRefinement;
        fprintf(['WNL full eigenpair refinement (%s): lambda shift ', ...
            '= %.6g%+.6gi, scaled residual %.3e -> %.3e, ', ...
            'Newton steps = %d in %d pass(es), eigen-tolerance ', ...
            'converged = %d, direct coefficient-residual ready = %d\n'], ...
            spec.label, ...
            real(refinement.lambdaShift),imag(refinement.lambdaShift), ...
            refinement.initialResidual,refinement.finalResidual, ...
            refinement.steps,refinement.numberOfPasses, ...
            refinement.converged,refinement.directResidualReady);
        fprintf('  eigenpair refinement stop reason: %s\n', ...
            refinement.stopReason);
        if isfield(refinement,'phaseConstraintSource')
            fprintf('  eigenpair phase/scale anchor: %s\n', ...
                refinement.phaseConstraintSource);
        end
    end
    eigenpairRefinementSeconds = toc(eigenpairWallClock);
end

adjointWallClock = tic;
if ~isempty(opts.left)
    left = opts.left(:);
elseif isfield(spec, 'left') && ~isempty(spec.left)
    left = spec.left(:);
elseif tracking.used
    % Solve the exactly normalized bordered adjoint equations
    %
    %   A'*left + directUnit*alpha = 0,
    %   (Bslow*directUnit)'*left = 1.
    %
    % Multiplication of the first row by the direct null vector forces the
    % border multiplier alpha to zero at exact neutrality.  Unlike the
    % earlier penalty-constrained least-squares solve, this formulation
    % removes the null direction without introducing a large artificial
    % constraint weight.  It is substantially better conditioned for the
    % primitive velocity-pressure descriptor matrix.
    [left, leftSingularValue, tracking.left] = ...
        bordered_adjoint_null(block.A, block.Bslow, direct, spec, opts);
    if opts.verbose
        fprintf(['WNL bordered adjoint solve (%s): effective sigma = ', ...
            '%.3e, scaled residual = %.3e, method = %s, flag = %d, ', ...
            'iterations = %d, restarts = %d, constraint residual = ', ...
            '%.3e, valid = %d\n'], ...
            spec.label, leftSingularValue, ...
            tracking.left.scaledResidual, tracking.left.solver, ...
            tracking.left.flag, ...
            tracking.left.iterations, tracking.left.restarts, ...
            tracking.left.constraintResidual, ...
            tracking.left.candidateValid);
    end
else
    [~, leftSingularValue, left] = smallest_svd(block.A', opts);
end
adjointSeconds = toc(adjointWallClock);

if numel(left) ~= size(block.A, 1)
    error('wnl_compute_mode:LeftSize', ...
        'Left vector has %d entries; block requires %d.', ...
        numel(left), size(block.A, 1));
end

normalization = left' * (block.Bslow * direct);
if ~isfinite(real(normalization)) || ~isfinite(imag(normalization))
    error('wnl_compute_mode:NonfiniteNormalization', ...
        ['The adjoint reconstruction produced a nonfinite descriptor ', ...
         'pairing. Inspect the bordered-solver flag, normalization-row ', ...
         'residual, and temporal-block regularization diagnostics.']);
end
if abs(normalization) < opts.nullTolerance * norm(left) * ...
        max(norm(block.Bslow * direct), eps)
    error('wnl_compute_mode:ZeroNormalization', ...
        ['The direct/left pair has a nearly zero descriptor pairing. ', ...
         'The selected null vectors may belong to different modes.']);
end
left = left / conj(normalization);

[directResidual,directResidualDetails] = wnl_descriptor_residual( ...
    block.A,block.Bslow,direct,'direct');
[leftResidual,leftResidualDetails] = wnl_descriptor_residual( ...
    block.A,block.Bslow,left,'adjoint');

mode = struct();
mode.spec = spec;
mode.block = block;
mode.vector = direct;
mode.field = wnl_make_field(spec, direct);
mode.left = left;
mode.leftField = wnl_make_field(spec, left);
mode.normalization = left' * (block.Bslow * direct);
mode.directResidual = directResidual;
mode.leftResidual = leftResidual;
mode.directResidualDetails = directResidualDetails;
mode.leftResidualDetails = leftResidualDetails;
mode.directSingularValue = directSingularValue;
mode.leftSingularValue = leftSingularValue;
mode.tracking = tracking;
mode.timing = struct('directSolveSeconds',directSolveSeconds, ...
    'eigenpairRefinementSeconds',eigenpairRefinementSeconds, ...
    'adjointSeconds',adjointSeconds,'totalSeconds',toc(modeWallClock));

if opts.verbose
    fprintf(['WNL mode %s: direct residual %.3e, left residual %.3e, ', ...
        '<left,Bslow*direct> = %.6g%+.6gi\n'], ...
        spec.label, directResidual, leftResidual, ...
        real(mode.normalization), imag(mode.normalization));
    if directResidualDetails.fullToPhysicalNormRatio > 10
        fprintf(['  direct algebraic/full-state norm inflation = ', ...
            '%.3e (excluded from the residual denominator)\n'], ...
            directResidualDetails.fullToPhysicalNormRatio);
    end
    fprintf(['WNL mode timing %s: direct %.3f s, eigenpair %.3f s, ', ...
        'adjoint %.3f s, total %.3f s\n'],spec.label, ...
        mode.timing.directSolveSeconds, ...
        mode.timing.eigenpairRefinementSeconds, ...
        mode.timing.adjointSeconds,mode.timing.totalSeconds);
end
end

function combined = combine_refinement_passes(firstPass,secondPass,opts)
combined = secondPass;
combined.initialLambda = firstPass.initialLambda;
combined.initialResidual = firstPass.initialResidual;
combined.lambdaShift = secondPass.finalLambda-firstPass.initialLambda;
combined.steps = firstPass.steps+secondPass.steps;
combined.totalIterations = firstPass.totalIterations+ ...
    secondPass.totalIterations;
combined.lastFlag = secondPass.lastFlag;
combined.converged = secondPass.converged;
combined.escalated = true;
combined.numberOfPasses = 2;
combined.directResidualReady = secondPass.finalResidual <= ...
    opts.coefficientModeResidualTolerance;
combined.residualHistory = [firstPass.residualHistory; ...
    secondPass.residualHistory(2:end)];
combined.lambdaHistory = [firstPass.lambdaHistory; ...
    secondPass.lambdaHistory(2:end)];
combined.linearSolveResidualHistory = [ ...
    firstPass.linearSolveResidualHistory; ...
    secondPass.linearSolveResidualHistory];
combined.stepLengthHistory = [firstPass.stepLengthHistory; ...
    secondPass.stepLengthHistory];
combined.solverHistory = [firstPass.solverHistory; ...
    secondPass.solverHistory];
combined.algebraicCompletionHistory = [ ...
    firstPass.algebraicCompletionHistory; ...
    secondPass.algebraicCompletionHistory];
combined.lastAlgebraicCompletion = ...
    secondPass.lastAlgebraicCompletion;
combined.phaseConstraintResidualHistory = [ ...
    firstPass.phaseConstraintResidualHistory; ...
    secondPass.phaseConstraintResidualHistory(2:end)];
combined.descriptorRetentionHistory = [ ...
    firstPass.descriptorRetentionHistory; ...
    secondPass.descriptorRetentionHistory(2:end)];
combined.descriptorOverlapHistory = [ ...
    firstPass.descriptorOverlapHistory; ...
    secondPass.descriptorOverlapHistory(2:end)];
combined.minimumDescriptorRetention = min( ...
    combined.descriptorRetentionHistory);
combined.minimumDescriptorOverlap = min( ...
    combined.descriptorOverlapHistory);
combined.stoppedForReferenceMismatch = ...
    firstPass.stoppedForReferenceMismatch || ...
    secondPass.stoppedForReferenceMismatch;
combined.referenceDiagnostic = eigenpair_reference_diagnostic( ...
    firstPass.initialLambda,secondPass.finalLambda,opts);
combined.firstPass = firstPass;
combined.continuationPass = secondPass;
end

function [spec,block,direct,information] = ...
        refine_operating_point_eigenpair(model,spec,block,direct,opts)
% Joint Newton correction for A(lambda)*phi=0 with a phase/scale border.
validate_eigenpair_refinement_options(opts);
initialLambda = wnl_spec_lambda(spec);
referenceLambda = initialLambda;
if ~isempty(opts.eigenpairReferenceLambda)
    referenceLambda = opts.eigenpairReferenceLambda;
end
initialResidual = scaled_direct_residual(block,direct);
referenceDirect = direct;
referenceDirectNorm = norm(referenceDirect);
if ~isfinite(referenceDirectNorm) || referenceDirectNorm <= eps
    error('wnl_compute_mode:PhysicalModeLost', ...
        ['The operating-point refinement seed is zero or nonfinite. ', ...
         'It cannot define the eigenvector phase/scale constraint.']);
end
referenceDescriptor = block.Bslow*referenceDirect;
referenceDescriptorNorm = norm(referenceDescriptor);
referenceDescriptorRatio = referenceDescriptorNorm/referenceDirectNorm;
if ~isfinite(referenceDescriptorNorm) || ...
        referenceDescriptorNorm <= eps
    error('wnl_compute_mode:PhysicalModeLost', ...
        ['The operating-point refinement seed has Bslow*phi=0. ', ...
         'It is an algebraic/gauge direction rather than a physical ', ...
         'Floquet mode with a slow-time descriptor component.']);
end
[phaseRow,phaseTarget,phaseSource] = physical_eigenvector_phase_row( ...
    block,referenceDirect,spec,referenceDescriptor, ...
    referenceDescriptorNorm);
bestResidual = initialResidual;
bestDirect = direct;
bestSpec = spec;
bestBlock = block;
totalIterations = 0;
steps = 0;
lastFlag = NaN;
residualHistory = initialResidual;
lambdaHistory = initialLambda;
linearSolveResidualHistory = zeros(0,1);
stepLengthHistory = zeros(0,1);
solverHistory = cell(0,1);
algebraicCompletionHistory = cell(0,1);
lastAlgebraicCompletion = struct('attempted',false, ...
    'totalIterations',0);
lastCorrectionInformation = struct('available',false, ...
    'trialAvailable',false);
lastCorrectionTrial = struct('accepted',false,'bestResidual',Inf, ...
    'bestDescriptorRetention',0,'bestDescriptorOverlap',0, ...
    'usedAlgebraicCompletion',false);
phaseConstraintResidualHistory = abs(phaseRow*direct-phaseTarget);
descriptorRetentionHistory = 1.0;
descriptorOverlapHistory = 1.0;
stagnationCount = 0;
stoppedForReferenceMismatch = false;
skippedForInaccurateSeed = initialResidual > ...
    opts.eigenpairMaximumSeedResidualRatio*opts.modeResidualTolerance;
if skippedForInaccurateSeed
    stopReason = ['refinement skipped because the lifted mode is not a ', ...
        'safe physical Newton seed'];
    numberOfNewtonSteps = 0;
elseif initialResidual <= opts.eigenpairRefinementTolerance
    stopReason = 'eigenpair residual tolerance reached';
    numberOfNewtonSteps = 0;
else
    stopReason = 'Newton-step budget exhausted';
    numberOfNewtonSteps = opts.eigenpairRefinementMaxSteps;
end
for newtonStep = 1:numberOfNewtonSteps
    currentResidual = scaled_direct_residual(block,direct);
    if currentResidual <= opts.eigenpairRefinementTolerance
        stopReason = 'eigenpair residual tolerance reached';
        break;
    end
    [gmresCorrection,gmresInformation] = ...
        solve_eigenpair_correction(block,direct,spec,phaseRow, ...
        phaseTarget,opts,'gmres',[]);
    totalIterations = totalIterations+gmresInformation.iterations;
    correctionInformation = gmresInformation;
    correctionTrial = try_eigenpair_correction(model,block,direct, ...
        spec,gmresCorrection,gmresInformation,currentResidual,phaseRow, ...
        phaseTarget,referenceDescriptor,referenceDescriptorNorm, ...
        referenceDescriptorRatio,opts);
    if correctionTrial.algebraicCompletion.attempted
        totalIterations = totalIterations + ...
            correctionTrial.algebraicCompletion.totalIterations;
        gmresInformation.algebraicCompletion = ...
            correctionTrial.algebraicCompletion;
        if correctionTrial.usedAlgebraicCompletion
            gmresInformation.solver = ...
                [gmresInformation.solver,' + DAE algebraic completion'];
        end
    end
    correctionInformation = gmresInformation;
    if opts.verbose && correction_candidate_available(gmresInformation)
        fprintf(['WNL block-GMRES physical trial: accepted=%d, ', ...
            'best residual %.3e, descriptor retention/overlap ', ...
            '%.3e/%.3e, equation gate=%d, ', ...
            'algebraic completion=%d.\n'], ...
            correctionTrial.accepted, ...
            correctionTrial.bestResidual, ...
            correctionTrial.bestDescriptorRetention, ...
            correctionTrial.bestDescriptorOverlap, ...
            gmresInformation.available, ...
            correctionTrial.usedAlgebraicCompletion);
    elseif opts.verbose && isfield(gmresInformation,'rejectionReason') && ...
            ~isempty(gmresInformation.rejectionReason)
        fprintf('WNL block-GMRES correction unavailable: %s.\n', ...
            gmresInformation.rejectionReason);
    end

    % Do not spend LSQR work merely because GMRES missed an algebraic
    % tolerance. First test whether its inexact correction actually reduces
    % the full physical residual on the tracked descriptor branch. Only a
    % rejected physical trial activates the fallback.
    if ~correctionTrial.accepted && ...
            opts.eigenpairLsqrFallbackMaxIterations > 0
        warmStart = [];
        % Reuse a rejected GMRES correction only when its best physical
        % trial remained on the descriptor branch. A pressure-inflated
        % correction is a harmful LSQR initial iterate and defeats the
        % physical minimum-norm fallback introduced below.
        if correction_candidate_available(gmresInformation) && ...
                correctionTrial.bestDescriptorRetention >= ...
                    opts.eigenpairMinimumDescriptorRetention && ...
                correctionTrial.bestDescriptorOverlap >= ...
                    opts.eigenpairMinimumDescriptorOverlap
            warmStart = gmresCorrection;
        end
        [lsqrCorrection,lsqrInformation] = ...
            solve_eigenpair_correction(block,direct,spec,phaseRow, ...
            phaseTarget,opts,'lsqr',warmStart);
        totalIterations = totalIterations+lsqrInformation.iterations;
        lsqrTrial = try_eigenpair_correction(model,block,direct, ...
            spec,lsqrCorrection,lsqrInformation,currentResidual, ...
            phaseRow,phaseTarget,referenceDescriptor, ...
            referenceDescriptorNorm,referenceDescriptorRatio,opts);
        if lsqrTrial.algebraicCompletion.attempted
            totalIterations = totalIterations + ...
                lsqrTrial.algebraicCompletion.totalIterations;
            lsqrInformation.algebraicCompletion = ...
                lsqrTrial.algebraicCompletion;
            if lsqrTrial.usedAlgebraicCompletion
                lsqrInformation.solver = ...
                    [lsqrInformation.solver, ...
                    ' + DAE algebraic completion'];
            end
        end
        if opts.verbose && correction_candidate_available(lsqrInformation)
            fprintf(['WNL LSQR fallback physical trial: accepted=%d, ', ...
                'best residual %.3e, descriptor retention/overlap ', ...
                '%.3e/%.3e, equation gate=%d, ', ...
                'algebraic completion=%d.\n'], ...
                lsqrTrial.accepted, ...
                lsqrTrial.bestResidual, ...
                lsqrTrial.bestDescriptorRetention, ...
                lsqrTrial.bestDescriptorOverlap, ...
                lsqrInformation.available, ...
                lsqrTrial.usedAlgebraicCompletion);
        elseif opts.verbose && ...
                isfield(lsqrInformation,'rejectionReason') && ...
                ~isempty(lsqrInformation.rejectionReason)
            fprintf('WNL LSQR correction unavailable: %s.\n', ...
                lsqrInformation.rejectionReason);
        end
        if lsqrTrial.accepted || ...
                lsqrTrial.bestResidual < correctionTrial.bestResidual
            correctionTrial = lsqrTrial;
            correctionInformation = lsqrInformation;
        elseif ~correctionTrial.accepted && ...
                ~lsqrInformation.available && ...
                correctionTrial.bestDescriptorRetention < ...
                    opts.eigenpairMinimumDescriptorRetention
            % The fast correction solved its equation but left the physical
            % branch, while the pressure-safe fallback did not solve the
            % equation. Retain the fallback diagnostics so the stop reason
            % identifies algebraic nonconvergence rather than suggesting
            % that more line-search cuts will help.
            correctionTrial = lsqrTrial;
            correctionInformation = lsqrInformation;
        end
    end
    lastFlag = correctionInformation.flag;
    lastAlgebraicCompletion = correctionTrial.algebraicCompletion;
    lastCorrectionInformation = correctionInformation;
    lastCorrectionTrial = summarize_correction_trial(correctionTrial);
    accepted = correctionTrial.accepted;
    if ~accepted
        if ~correctionInformation.available
            stopReason = ['bordered correction equation did not reach ', ...
                'the required inexact-Newton tolerance'];
        else
            stopReason = ['bordered correction did not reduce the ', ...
                'residual while preserving the physical descriptor mode'];
        end
        if opts.verbose
            fprintf(['WNL eigenpair correction rejected (%s): ', ...
                'correction residual %.3e (scaled %.3e, phase %.3e), ', ...
                'best trial residual %.3e versus %.3e, descriptor ', ...
                'retention/overlap %.3e/%.3e.\n'], ...
                correctionInformation.solver, ...
                correctionInformation.equationResidual, ...
                correctionInformation.scaledEquationResidual, ...
                correctionInformation.phaseConstraintResidual, ...
                correctionTrial.bestResidual,currentResidual, ...
                correctionTrial.bestDescriptorRetention, ...
                correctionTrial.bestDescriptorOverlap);
        end
        break;
    end
    candidateDirect = correctionTrial.direct;
    candidateSpec = correctionTrial.spec;
    candidateBlock = correctionTrial.block;
    candidateResidual = correctionTrial.residual;
    candidatePhaseResidual = correctionTrial.phaseResidual;
    candidateDescriptorRetention = ...
        correctionTrial.descriptorRetention;
    candidateDescriptorOverlap = correctionTrial.descriptorOverlap;
    stepLength = correctionTrial.stepLength;
    relativeImprovement = ...
        (currentResidual-candidateResidual)/max(currentResidual,eps);
    direct = candidateDirect;
    spec = candidateSpec;
    block = candidateBlock;
    steps = newtonStep;
    residualHistory(end+1,1) = candidateResidual; %#ok<AGROW>
    lambdaHistory(end+1,1) = wnl_spec_lambda(spec); %#ok<AGROW>
    linearSolveResidualHistory(end+1,1) = ...
        correctionInformation.equationResidual; %#ok<AGROW>
    stepLengthHistory(end+1,1) = stepLength; %#ok<AGROW>
    solverHistory{end+1,1} = correctionInformation.solver; %#ok<AGROW>
    algebraicCompletionHistory{end+1,1} = ...
        correctionTrial.algebraicCompletion; %#ok<AGROW>
    phaseConstraintResidualHistory(end+1,1) = ...
        candidatePhaseResidual; %#ok<AGROW>
    descriptorRetentionHistory(end+1,1) = ...
        candidateDescriptorRetention; %#ok<AGROW>
    descriptorOverlapHistory(end+1,1) = ...
        candidateDescriptorOverlap; %#ok<AGROW>
    if opts.verbose
        fprintf(['WNL eigenpair step %d: %s, correction residual ', ...
            '%.3e (scaled %.3e, phase %.3e), step %.3g, ', ...
            'mode residual %.3e -> %.3e, ', ...
            'descriptor retention/overlap %.3e/%.3e, ', ...
            'lambda %.8g%+.3gi\n'],newtonStep, ...
            correctionInformation.solver, ...
            correctionInformation.equationResidual, ...
            correctionInformation.scaledEquationResidual, ...
            correctionInformation.phaseConstraintResidual,stepLength, ...
            currentResidual,candidateResidual, ...
            candidateDescriptorRetention,candidateDescriptorOverlap, ...
            real(wnl_spec_lambda(spec)), ...
            imag(wnl_spec_lambda(spec)));
    end
    if candidateResidual < bestResidual
        bestResidual = candidateResidual;
        bestDirect = direct;
        bestSpec = spec;
        bestBlock = block;
    end
    if relativeImprovement < ...
            opts.eigenpairStagnationRelativeImprovement
        stagnationCount = stagnationCount+1;
    else
        stagnationCount = 0;
    end
    if stagnationCount >= opts.eigenpairStagnationSteps
        stopReason = 'physical residual stagnated';
        break;
    end
    referenceDiagnostic = eigenpair_reference_diagnostic( ...
        referenceLambda,wnl_spec_lambda(spec),opts);
    lastLambdaStep = abs(lambdaHistory(end)-lambdaHistory(end-1));
    totalLambdaShift = abs(wnl_spec_lambda(spec)-referenceLambda);
    exponentShiftStable = lastLambdaStep <= ...
        opts.eigenpairReferenceMismatchMaximumLastStepRatio * ...
        max(totalLambdaShift,eps);
    reliableMismatch = candidateResidual <= ...
        opts.modeResidualTolerance && ...
        exponentShiftStable && ...
        referenceDiagnostic.absoluteMismatch > ...
        opts.eigenpairReferenceMismatchAbortFactor * ...
        referenceDiagnostic.allowedMismatch;
    if opts.enforceReducedFullEigenvalueAgreement && ...
            opts.stopEigenpairOnReferenceMismatch && ...
            (opts.eigenpairPriorAcceptedSteps+newtonStep) >= ...
                opts.eigenpairReferenceMismatchMinimumSteps && ...
            reliableMismatch
        stoppedForReferenceMismatch = true;
        stopReason = ['reduced/full exponent mismatch established at ', ...
            'linear-ready residual'];
        break;
    end
    if candidateResidual <= opts.eigenpairRefinementTolerance
        stopReason = 'eigenpair residual tolerance reached';
        break;
    end
end
direct = bestDirect;
spec = bestSpec;
block = bestBlock;
referenceDiagnostic = eigenpair_reference_diagnostic( ...
    referenceLambda,wnl_spec_lambda(spec),opts);
information = struct('attempted',true,'initialLambda',initialLambda, ...
    'referenceLambda',referenceLambda, ...
    'finalLambda',wnl_spec_lambda(spec), ...
    'lambdaShift',wnl_spec_lambda(spec)-initialLambda, ...
    'initialResidual',initialResidual,'finalResidual',bestResidual, ...
    'steps',steps,'totalIterations',totalIterations, ...
    'lastFlag',lastFlag,'converged', ...
    bestResidual <= opts.eigenpairRefinementTolerance, ...
    'residualHistory',residualHistory, ...
    'lambdaHistory',lambdaHistory, ...
    'linearSolveResidualHistory',linearSolveResidualHistory, ...
    'stepLengthHistory',stepLengthHistory, ...
    'solverHistory',{solverHistory}, ...
    'algebraicCompletionHistory',{algebraicCompletionHistory}, ...
    'lastAlgebraicCompletion',lastAlgebraicCompletion, ...
    'lastCorrectionInformation',lastCorrectionInformation, ...
    'lastCorrectionTrial',lastCorrectionTrial, ...
    'phaseConstraintResidualHistory', ...
        phaseConstraintResidualHistory, ...
    'descriptorRetentionHistory',descriptorRetentionHistory, ...
    'descriptorOverlapHistory',descriptorOverlapHistory, ...
    'minimumDescriptorRetention',min(descriptorRetentionHistory), ...
    'minimumDescriptorOverlap',min(descriptorOverlapHistory), ...
    'skippedForInaccurateSeed',skippedForInaccurateSeed, ...
    'phaseConstraintSource',phaseSource, ...
    'stoppedForReferenceMismatch',stoppedForReferenceMismatch, ...
    'referenceDiagnostic',referenceDiagnostic, ...
    'stopReason',stopReason);
end

function [phaseRow,phaseTarget,source] = ...
        physical_eigenvector_phase_row(block,direct,spec,descriptor, ...
        descriptorNorm)
% Anchor scale to interface displacement, never to pressure-dominated norm.
numberOfUnknowns = numel(direct);
phaseRow = sparse(1,numberOfUnknowns);
source = 'Bslow descriptor variables';
if isfield(spec,'prescribedDofs') && ~isempty(spec.prescribedDofs)
    localDofs = unique(spec.prescribedDofs(:));
    offsets = (0:numel(spec.n)-1)*spec.ndof;
    anchorDofs = reshape(localDofs+offsets,[],1);
    anchor = direct(anchorDofs);
    anchorNormSquared = real(anchor'*anchor);
    if isfinite(anchorNormSquared) && anchorNormSquared > eps
        phaseRow(1,anchorDofs) = anchor'/anchorNormSquared;
        source = 'prescribed interface displacement';
    end
end
if nnz(phaseRow) == 0
    % Bslow removes pressure and algebraic constraint variables. This is the
    % physical fallback for models without explicit interface DOF metadata.
    phaseRow = sparse((descriptor'/descriptorNorm^2)*block.Bslow);
end
phaseTarget = phaseRow*direct;
if ~isfinite(real(phaseTarget)) || ~isfinite(imag(phaseTarget)) || ...
        abs(phaseTarget) <= eps
    error('wnl_compute_mode:PhysicalModeLost', ...
        ['The physical interface/descriptor variables cannot define a ', ...
         'finite eigenvector phase and scale.']);
end
phaseRow = phaseRow/phaseTarget;
phaseTarget = 1.0;
end

function trial = try_eigenpair_correction(model,block,direct,spec, ...
        correction,information,currentResidual,phaseRow,phaseTarget, ...
        referenceDescriptor,referenceDescriptorNorm, ...
        referenceDescriptorRatio,opts)
% Test an inexact correction against the actual physical Floquet operator.
trial = struct('accepted',false,'direct',direct,'spec',spec, ...
    'block',block,'residual',Inf,'phaseResidual',Inf, ...
    'descriptorRetention',0,'descriptorOverlap',0, ...
    'stepLength',0,'bestResidual',Inf, ...
    'bestDescriptorRetention',0,'bestDescriptorOverlap',0, ...
    'usedAlgebraicCompletion',false, ...
    'algebraicCompletion',struct('attempted',false, ...
    'totalIterations',0));
if ~correction_candidate_available(information)
    return;
end
numberOfUnknowns = numel(direct);
stepLength = 1.0;
algebraicCompletionAttempted = false;
for lineSearchCut = 0:opts.eigenpairLineSearchMaxCuts
    candidateDirect = direct + ...
        stepLength*correction(1:numberOfUnknowns);
    candidateSpec = spec;
    candidateSpec.lambda = wnl_spec_lambda(spec) + ...
        stepLength*correction(end);
    candidateBlock = model.block(candidateSpec);
    candidateResidual = scaled_direct_residual( ...
        candidateBlock,candidateDirect);
    candidatePhaseResidual = abs( ...
        phaseRow*candidateDirect-phaseTarget);
    candidateDescriptor = candidateBlock.Bslow*candidateDirect;
    candidateDirectNorm = norm(candidateDirect);
    candidateDescriptorNorm = norm(candidateDescriptor);
    candidateDescriptorRatio = candidateDescriptorNorm/max( ...
        candidateDirectNorm,eps);
    candidateDescriptorRetention = candidateDescriptorRatio/max( ...
        referenceDescriptorRatio,eps);
    candidateDescriptorOverlap = abs( ...
        referenceDescriptor'*candidateDescriptor)/max( ...
        referenceDescriptorNorm*candidateDescriptorNorm,eps);
    physicalCandidate = isfinite(candidateDirectNorm) && ...
        candidateDirectNorm > eps && ...
        isfinite(candidatePhaseResidual) && ...
        candidatePhaseResidual <= ...
            opts.eigenpairCorrectionConstraintTolerance && ...
        isfinite(candidateDescriptorRetention) && ...
        candidateDescriptorRetention >= ...
            opts.eigenpairMinimumDescriptorRetention && ...
        isfinite(candidateDescriptorOverlap) && ...
        candidateDescriptorOverlap >= ...
            opts.eigenpairMinimumDescriptorOverlap;

    % A block-preconditioned correction can accurately update the dynamic
    % velocity/interface state while acquiring an enormous pressure or
    % gauge component. If its physical residual decreases and its Bslow
    % direction is correct, recompute only the zero-mass algebraic variables
    % by a minimum-norm DAE completion. The descriptor-supported variables,
    % interface phase/scale, lambda, and every governing row remain fixed.
    inflatedAlgebraicState = ~physicalCandidate && ...
        isfinite(candidateResidual) && ...
        candidateResidual < currentResidual && ...
        isfinite(candidatePhaseResidual) && ...
        candidatePhaseResidual <= ...
            opts.eigenpairCorrectionConstraintTolerance && ...
        isfinite(candidateDescriptorOverlap) && ...
        candidateDescriptorOverlap >= ...
            opts.eigenpairMinimumDescriptorOverlap && ...
        isfinite(candidateDescriptorRetention) && ...
        candidateDescriptorRetention < ...
            opts.eigenpairMinimumDescriptorRetention;
    if opts.eigenpairUseAlgebraicCompletion && ...
            inflatedAlgebraicState && ~algebraicCompletionAttempted
        algebraicCompletionAttempted = true;
        preservedDofs = expanded_prescribed_dofs(candidateSpec);
        try
            [completedDirect,completionInformation] = ...
                wnl_complete_algebraic_state(candidateBlock.A, ...
                candidateBlock.Bslow,candidateDirect,preservedDofs,opts);
        catch completionError
            completedDirect = candidateDirect;
            completionInformation = struct('attempted',true, ...
                'available',false,'valid',false,'totalIterations',0, ...
                'initialResidualNorm',norm( ...
                    candidateBlock.A*candidateDirect), ...
                'finalResidualNorm',Inf, ...
                'initialFullNorm',norm(candidateDirect), ...
                'finalFullNorm',Inf, ...
                'errorIdentifier',completionError.identifier, ...
                'errorMessage',completionError.message);
            if opts.verbose
                warning('wnl_compute_mode:AlgebraicCompletionFailed', ...
                    'DAE algebraic completion failed: %s', ...
                    completionError.message);
            end
        end
        trial.algebraicCompletion = completionInformation;
        if opts.verbose && completionInformation.attempted
            fprintf(['WNL DAE algebraic completion: residual norm ', ...
                '%.3e -> %.3e, full-state norm %.3e -> %.3e, ', ...
                'iterations = %d, available/valid = %d/%d.\n'], ...
                completionInformation.initialResidualNorm, ...
                completionInformation.finalResidualNorm, ...
                completionInformation.initialFullNorm, ...
                completionInformation.finalFullNorm, ...
                completionInformation.totalIterations, ...
                completionInformation.available, ...
                completionInformation.valid);
        end
        if completionInformation.available && ...
                completionInformation.valid
            completedResidual = scaled_direct_residual( ...
                candidateBlock,completedDirect);
            completedPhaseResidual = abs( ...
                phaseRow*completedDirect-phaseTarget);
            completedDescriptor = ...
                candidateBlock.Bslow*completedDirect;
            completedDirectNorm = norm(completedDirect);
            completedDescriptorNorm = norm(completedDescriptor);
            completedDescriptorRatio = completedDescriptorNorm / ...
                max(completedDirectNorm,eps);
            completedDescriptorRetention = ...
                completedDescriptorRatio/max(referenceDescriptorRatio,eps);
            completedDescriptorOverlap = abs( ...
                referenceDescriptor'*completedDescriptor) / max( ...
                referenceDescriptorNorm*completedDescriptorNorm,eps);
            completedPhysicalCandidate = ...
                isfinite(completedDirectNorm) && ...
                completedDirectNorm > eps && ...
                isfinite(completedPhaseResidual) && ...
                completedPhaseResidual <= ...
                    opts.eigenpairCorrectionConstraintTolerance && ...
                isfinite(completedDescriptorRetention) && ...
                completedDescriptorRetention >= ...
                    opts.eigenpairMinimumDescriptorRetention && ...
                isfinite(completedDescriptorOverlap) && ...
                completedDescriptorOverlap >= ...
                    opts.eigenpairMinimumDescriptorOverlap;
            if completedPhysicalCandidate && ...
                    isfinite(completedResidual) && ...
                    completedResidual < currentResidual
                candidateDirect = completedDirect;
                candidateResidual = completedResidual;
                candidatePhaseResidual = completedPhaseResidual;
                candidateDirectNorm = completedDirectNorm;
                candidateDescriptorNorm = completedDescriptorNorm;
                candidateDescriptorRetention = ...
                    completedDescriptorRetention;
                candidateDescriptorOverlap = completedDescriptorOverlap;
                physicalCandidate = true;
                trial.usedAlgebraicCompletion = true;
            end
        end
    end
    if isfinite(candidateResidual) && candidateResidual < trial.bestResidual
        trial.bestResidual = candidateResidual;
        trial.bestDescriptorRetention = candidateDescriptorRetention;
        trial.bestDescriptorOverlap = candidateDescriptorOverlap;
    end
    if physicalCandidate && isfinite(candidateResidual) && ...
            candidateResidual < currentResidual
        trial.accepted = true;
        trial.direct = candidateDirect;
        trial.spec = candidateSpec;
        trial.block = candidateBlock;
        trial.residual = candidateResidual;
        trial.phaseResidual = candidatePhaseResidual;
        trial.descriptorRetention = candidateDescriptorRetention;
        trial.descriptorOverlap = candidateDescriptorOverlap;
        trial.stepLength = stepLength;
        return;
    end
    stepLength = 0.5*stepLength;
end
end

