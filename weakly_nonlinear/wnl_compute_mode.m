function [left, sigma, information] = ...
        bordered_adjoint_null(A, Bslow, direct, spec, opts)
%BORDERED_ADJOINT_NULL Solve the normalized algebraic adjoint equations.
%
% For a simple neutral mode, the bordered matrix
%
%   [ A'                 directUnit ]
%   [ pairingUnit'          0       ]
%
% is nonsingular even though A is singular. Here
% pairingUnit=Bslow*direct/||Bslow*direct||. The final normalization in the
% caller converts this convenient unit constraint to
% left'*Bslow*direct=1.

numberOfUnknowns = size(A, 1);
[~,directResidualDetails] = wnl_descriptor_residual( ...
    A,Bslow,direct,'direct');
directNorm = directResidualDetails.physicalVectorNorm;
if ~isfinite(directNorm) || directNorm <= eps
    error('wnl_compute_mode:ZeroDirectForAdjoint', ...
        ['The direct vector has no finite physical descriptor-supported ', ...
         'component, so the adjoint cannot be paired.']);
end
directUnit = direct/directNorm;
pairing = Bslow*directUnit;
pairingNorm = norm(pairing);
if pairingNorm <= eps
    error('wnl_compute_mode:ZeroDescriptorPairingSeed', ...
        ['Bslow*direct is zero. The selected direct mode has no slow-time ', ...
         'descriptor component and cannot define a Landau solvability ', ...
         'normalization.']);
end
pairingUnit = pairing/pairingNorm;

validateattributes(opts.modeTrackingSolveTolerance, {'numeric'}, ...
    {'scalar', 'real', 'positive', 'finite'});
validateattributes(opts.modeTrackingMaxIterations, {'numeric'}, ...
    {'scalar', 'real', 'integer', 'positive'});
validateattributes(opts.adjointBorderedMaxRestarts, {'numeric'}, ...
    {'scalar', 'real', 'integer', 'nonnegative'});
validateattributes(opts.adjointGmresRestart, {'numeric'}, ...
    {'scalar', 'real', 'integer', 'positive'});
validateattributes(opts.adjointGmresMaxCycles, {'numeric'}, ...
    {'scalar', 'real', 'integer', 'positive'});
validateattributes(opts.adjointBlockRegularization, {'numeric'}, ...
    {'scalar', 'real', 'positive', 'finite'});
validateattributes(opts.adjointBlockRegularizationGrowth, {'numeric'}, ...
    {'scalar', 'real', '>', 1, 'finite'});
validateattributes(opts.adjointBlockRegularizationAttempts, {'numeric'}, ...
    {'scalar', 'real', 'integer', 'positive'});
validateattributes(opts.adjointBlockMaximumInverseGain, {'numeric'}, ...
    {'scalar', 'real', 'positive', 'finite'});
assert(islogical(opts.adjointUseBlockGmres) || ...
    (isnumeric(opts.adjointUseBlockGmres) && ...
    isscalar(opts.adjointUseBlockGmres)), ...
    'opts.adjointUseBlockGmres must be a logical scalar.');

borderedMatrix = [A', sparse(directUnit); ...
    sparse(pairingUnit'), sparse(1, 1)];
rightHandSide = [complex(zeros(numberOfUnknowns, 1)); 1];
[scaledMatrix, scaledRightHandSide, rowScale] = ...
    equilibrate_equations(borderedMatrix, rightHandSide);
[scaledMatrix, columnScale] = equilibrate_columns(scaledMatrix);

scaledSolution = complex(zeros(numberOfUnknowns+1, 1));
operatorScale = max(1.0,deterministic_matrix_scale(A));
% Construct the primary adjoint to the coefficient-level tolerance during
% the first solve. Stopping at the looser plotting/linear gate only to fail
% immediately in wnl_analyze_* wastes a complete mode reconstruction.
targetResidual = min(opts.modeResidualTolerance, ...
    opts.coefficientModeResidualTolerance);
constraintTolerance = max(targetResidual, ...
    100*opts.modeTrackingSolveTolerance);
flag = NaN;
relativeResidual = Inf;
totalIterations = 0;
restartsUsed = 0;
scaledResidual = Inf;
constraintResidual = Inf;
candidateValid = false;
left = complex(zeros(numberOfUnknowns, 1));
borderMultiplier = complex(NaN);
sigma = Inf;
solver = 'LSQR';
gmresInformation = struct();
gmresInformation.attempted = false;
gmresInformation.succeeded = false;

% The full Floquet matrix is block tridiagonal in temporal harmonic. Its
% diagonal blocks are the uncoupled spatial Stokes operators. Factor those
% blocks once and use their inverse inside a bordered block-Jacobi
% preconditioner.  The scalar Schur complement includes both the top border
% column and the normalization row.  This is important: treating the scalar
% border as an identity leaves the normalization residual essentially
% unpreconditioned even after the physical adjoint equation has improved.
numberOfHarmonics = numel(spec.n);
canUseBlockGmres = opts.adjointUseBlockGmres && ...
    numberOfHarmonics > 1 && ...
    spec.ndof*numberOfHarmonics == numberOfUnknowns;
if canUseBlockGmres
    gmresInformation.attempted = true;
    try
        if opts.verbose
            fprintf(['WNL adjoint preconditioner: factoring %d temporal ', ...
                'blocks of size %d.\n'], numberOfHarmonics, spec.ndof);
        end
        [blockFactors, blockRegularization, blockInverseGain] = ...
            factor_temporal_diagonal_blocks(scaledMatrix, spec.ndof, ...
            numberOfHarmonics, opts);
        [bottomBorder, borderResponse, borderSchur] = ...
            factor_bordered_block_jacobi(scaledMatrix, blockFactors, ...
            spec.ndof, numberOfHarmonics);
        if opts.verbose
            fprintf(['WNL adjoint preconditioner: regularization range ', ...
                '[%.3e, %.3e], maximum probe inverse gain %.3e.\n'], ...
                min(blockRegularization), max(blockRegularization), ...
                max(blockInverseGain));
            fprintf(['WNL adjoint preconditioner: bordered Schur ', ...
                'complement = %.6g%+.6gi.\n'], ...
                real(borderSchur), imag(borderSchur));
        end
        preconditioner = @(rightHandSideValue) ...
            apply_bordered_block_jacobi_inverse(rightHandSideValue, ...
            blockFactors, spec.ndof, numberOfHarmonics, ...
            bottomBorder, borderResponse, borderSchur);
        [scaledSolution, gmresFlag, gmresRelativeResidual, ...
            gmresIteration, gmresResidualHistory] = gmres( ...
            scaledMatrix, scaledRightHandSide, ...
            opts.adjointGmresRestart, ...
            opts.modeTrackingSolveTolerance, ...
            opts.adjointGmresMaxCycles, preconditioner, [], ...
            scaledSolution);
        physicalSolution = columnScale.*scaledSolution;
        left = physicalSolution(1:numberOfUnknowns);
        borderMultiplier = physicalSolution(end);
        [sigma, scaledResidual, constraintResidual, candidateValid] = ...
            adjoint_candidate_metrics(A, Bslow, left, borderMultiplier, ...
            pairingUnit, targetResidual, ...
            constraintTolerance, opts.nullTolerance);
        gmresIterations = gmres_iteration_count( ...
            gmresIteration, opts.adjointGmresRestart);
        totalIterations = gmresIterations;
        flag = gmresFlag;
        relativeResidual = gmresRelativeResidual;
        solver = 'block-GMRES';
        gmresInformation.flag = gmresFlag;
        gmresInformation.relativeResidual = gmresRelativeResidual;
        gmresInformation.iteration = gmresIteration;
        gmresInformation.iterations = gmresIterations;
        gmresInformation.residualHistory = gmresResidualHistory;
        % The physical residual and normalization row are the acceptance
        % tests.  A flag-1 (maximum Krylov cycles) candidate is still usable
        % when both of those independently evaluated tests pass.
        gmresInformation.succeeded = candidateValid;
        gmresInformation.candidateValid = candidateValid;
        gmresInformation.constraintResidual = constraintResidual;
        gmresInformation.blockRegularization = blockRegularization;
        gmresInformation.blockInverseGain = blockInverseGain;
        gmresInformation.borderSchurComplement = borderSchur;
        gmresInformation.preconditioner = ...
            'regularized bordered block-Jacobi';
    catch gmresError
        gmresInformation.succeeded = false;
        gmresInformation.errorIdentifier = gmresError.identifier;
        gmresInformation.errorMessage = gmresError.message;
        if opts.verbose
            warning('wnl_compute_mode:BlockGmresUnavailable', ...
                ['The temporal-block GMRES adjoint preconditioner could ', ...
                 'not be used (%s). Continuing with bordered LSQR.'], ...
                gmresError.message);
        end
    end
end

if ~candidateValid
    if opts.verbose && isfield(gmresInformation, 'flag')
        warning('wnl_compute_mode:BlockGmresCandidateRejected', ...
            ['Rejecting the block-GMRES adjoint candidate: flag %d, ', ...
             'scaled residual %.3e, normalization-row residual %.3e. ', ...
             'Continuing with bordered LSQR refinement.'], ...
            gmresInformation.flag, scaledResidual, constraintResidual);
    end
    if strcmp(solver, 'block-GMRES')
        solver = 'block-GMRES + LSQR refinement';
    end
    if any(~isfinite(real(scaledSolution))) || ...
            any(~isfinite(imag(scaledSolution)))
        scaledSolution = complex(zeros(numberOfUnknowns+1, 1));
    end
    for attempt = 0:opts.adjointBorderedMaxRestarts
        [scaledSolution, flag, relativeResidual, iterations] = lsqr( ...
            scaledMatrix, scaledRightHandSide, ...
            opts.modeTrackingSolveTolerance, ...
            opts.modeTrackingMaxIterations, [], [], scaledSolution);
        totalIterations = totalIterations+iterations;
        physicalSolution = columnScale.*scaledSolution;
        left = physicalSolution(1:numberOfUnknowns);
        borderMultiplier = physicalSolution(end);
        [sigma, scaledResidual, constraintResidual, candidateValid] = ...
            adjoint_candidate_metrics(A, Bslow, left, borderMultiplier, ...
            pairingUnit, targetResidual, ...
            constraintTolerance, opts.nullTolerance);
        restartsUsed = attempt;
        if candidateValid
            break;
        end
    end
end

information = struct();
information.method = 'exactly normalized bordered adjoint';
information.operatorScale = operatorScale;
information.effectiveSingularValue = sigma;
information.scaledResidual = scaledResidual;
information.borderMultiplier = borderMultiplier;
information.constraintResidual = constraintResidual;
information.constraintTolerance = constraintTolerance;
information.candidateValid = candidateValid;
information.solver = solver;
information.flag = flag;
information.relativeResidual = relativeResidual;
information.iterations = totalIterations;
information.restarts = restartsUsed;
information.maximumRestarts = opts.adjointBorderedMaxRestarts;
information.gmres = gmresInformation;
information.rowScaleRange = positive_range(rowScale);
information.columnScaleRange = positive_range(columnScale);

if ~candidateValid && opts.verbose
    warning('wnl_compute_mode:BorderedAdjointNotConverged', ...
        ['The bordered adjoint solver (%s) returned flag %d after %d ', ...
         'total iterations and %d restarts. Scaled adjoint residual ', ...
         '%.3e, normalization-row residual %.3e. The mode residual gate ', ...
         'will prevent nonlinear coefficients if this remains too large.'], ...
        solver, flag, totalIterations, restartsUsed, scaledResidual, ...
        constraintResidual);
end
end

function [factors, regularization, inverseGain] = ...
        factor_temporal_diagonal_blocks( ...
        borderedMatrix, ndof, numberOfHarmonics, opts)
factors = cell(numberOfHarmonics, 1);
regularization = zeros(numberOfHarmonics, 1);
inverseGain = inf(numberOfHarmonics, 1);
identity = speye(ndof);
probeIndex = (1:ndof).';
probe = [complex(ones(ndof, 1)), ...
    exp(1i*sqrt(2)*probeIndex)];
probeNorm = sqrt(sum(abs(probe).^2, 1));
for harmonicIndex = 1:numberOfHarmonics
    indices = (harmonicIndex-1)*ndof+(1:ndof);
    diagonalBlock = borderedMatrix(indices, indices);
    blockScale = max(deterministic_matrix_scale(diagonalBlock), 1.0);
    lastMessage = '';
    for attempt = 1:opts.adjointBlockRegularizationAttempts
        shift = opts.adjointBlockRegularization*blockScale * ...
            opts.adjointBlockRegularizationGrowth^(attempt-1);
        shiftedBlock = diagonalBlock+shift*identity;
        try
            trialFactor = decomposition(shiftedBlock, 'lu');
            trialSolution = trialFactor\probe;
            solutionNorm = sqrt(sum(abs(trialSolution).^2, 1));
            trialGain = max(solutionNorm./probeNorm);
            trialResidual = shiftedBlock*trialSolution-probe;
            relativeTrialResidual = max( ...
                sqrt(sum(abs(trialResidual).^2, 1))./probeNorm);
            finiteTrial = all(isfinite(real(trialSolution(:)))) && ...
                all(isfinite(imag(trialSolution(:))));
            if finiteTrial && ...
                    trialGain <= opts.adjointBlockMaximumInverseGain && ...
                    relativeTrialResidual <= 1.0e-5
                factors{harmonicIndex} = trialFactor;
                regularization(harmonicIndex) = shift;
                inverseGain(harmonicIndex) = trialGain;
                break;
            end
            lastMessage = sprintf([ ...
                'inverse gain %.3e, factor residual %.3e'], ...
                trialGain, relativeTrialResidual);
        catch factorError
            lastMessage = factorError.message;
        end
    end
    if isempty(factors{harmonicIndex})
        error('wnl_compute_mode:BlockPreconditionerFactorization', ...
            ['Could not construct a finite regularized inverse for ', ...
             'temporal block %d after %d attempts (%s).'], ...
            harmonicIndex, opts.adjointBlockRegularizationAttempts, ...
            lastMessage);
    end
end
end

function [bottomBorder, borderResponse, borderSchur] = ...
        factor_bordered_block_jacobi( ...
        borderedMatrix, factors, ndof, numberOfHarmonics)
numberOfSpatialUnknowns = ndof*numberOfHarmonics;
topBorder = borderedMatrix(1:numberOfSpatialUnknowns, end);
bottomBorder = borderedMatrix(end, 1:numberOfSpatialUnknowns);
borderResponse = apply_temporal_spatial_inverse( ...
    topBorder, factors, ndof, numberOfHarmonics);
borderSchur = bottomBorder*borderResponse;
schurScale = max(norm(bottomBorder)*norm(borderResponse), eps);
if ~isfinite(real(borderSchur)) || ~isfinite(imag(borderSchur)) || ...
        abs(borderSchur) <= 1.0e-12*schurScale
    error('wnl_compute_mode:BorderedPreconditionerSchurComplement', ...
        ['The regularized block-Jacobi bordered Schur complement is ', ...
         'zero, nonfinite, or numerically unresolved (|S|=%.3e, ', ...
         'scale=%.3e).'], abs(borderSchur), schurScale);
end
end

function result = apply_bordered_block_jacobi_inverse( ...
        rightHandSide, factors, ndof, numberOfHarmonics, ...
        bottomBorder, borderResponse, borderSchur)
numberOfSpatialUnknowns = ndof*numberOfHarmonics;
spatialRightHandSide = rightHandSide(1:numberOfSpatialUnknowns);
scalarRightHandSide = rightHandSide(end);
unborderedSolution = apply_temporal_spatial_inverse( ...
    spatialRightHandSide, factors, ndof, numberOfHarmonics);

% Invert [D c; p' 0] by its scalar Schur complement.  With
% z=D\f, v=D\c and S=p'*v,
%   alpha=(p'*z-g)/S,  x=z-v*alpha.
borderMultiplier = ...
    (bottomBorder*unborderedSolution-scalarRightHandSide)/borderSchur;
spatialSolution = unborderedSolution-borderResponse*borderMultiplier;
result = [spatialSolution; borderMultiplier];
if any(~isfinite(real(result))) || any(~isfinite(imag(result)))
    error('wnl_compute_mode:BlockPreconditionerNonfinite', ...
        ['The regularized bordered block-Jacobi inverse returned a ', ...
         'nonfinite value.']);
end
end

function result = apply_temporal_spatial_inverse( ...
        rightHandSide, factors, ndof, numberOfHarmonics)
numberOfSpatialUnknowns = ndof*numberOfHarmonics;
if size(rightHandSide, 1) ~= numberOfSpatialUnknowns
    error('wnl_compute_mode:BlockPreconditionerSize', ...
        ['The temporal spatial inverse received %d rows; expected %d.'], ...
        size(rightHandSide, 1), numberOfSpatialUnknowns);
end
result = complex(zeros(size(rightHandSide)));
for harmonicIndex = 1:numberOfHarmonics
    indices = (harmonicIndex-1)*ndof+(1:ndof);
    result(indices, :) = factors{harmonicIndex}\rightHandSide(indices, :);
end
if any(~isfinite(real(result))) || any(~isfinite(imag(result)))
    error('wnl_compute_mode:BlockPreconditionerNonfinite', ...
        'The regularized temporal-block inverse returned a nonfinite value.');
end
end

function [sigma, scaledResidual, constraintResidual, valid] = ...
        adjoint_candidate_metrics(A, Bslow, left, borderMultiplier, ...
        pairingUnit, targetResidual, constraintTolerance, nullTolerance)
finiteLeft = all(isfinite(real(left))) && all(isfinite(imag(left)));
finiteBorder = isfinite(real(borderMultiplier)) && ...
    isfinite(imag(borderMultiplier));
leftNorm = norm(left);
if ~finiteLeft || ~finiteBorder || ...
        ~isfinite(leftNorm) || leftNorm <= nullTolerance
    sigma = Inf;
    scaledResidual = Inf;
    constraintResidual = Inf;
    valid = false;
    return;
end
[scaledResidual,residualDetails] = wnl_descriptor_residual( ...
    A,Bslow,left,'adjoint');
sigma = residualDetails.effectiveResidual;
constraintResidual = abs(pairingUnit'*left-1);
valid = isfinite(sigma) && isfinite(scaledResidual) && ...
    isfinite(constraintResidual) && ...
    scaledResidual <= targetResidual && ...
    constraintResidual <= constraintTolerance;
end

function count = gmres_iteration_count(iteration, restart)
if isempty(iteration)
    count = 0;
elseif isscalar(iteration)
    count = iteration;
else
    % MATLAB reports [outer inner]. The current outer cycle has completed
    % only `inner` steps, whereas each preceding cycle completed `restart`.
    count = max(iteration(1)-1, 0)*restart+iteration(2);
end
end

function [vector, sigma, information] = ...
        tracked_constrained_null(block, seed, opts)
%TRACKED_CONSTRAINED_NULL Reconstruct a physical null direction.
%
% A primitive incompressible discretization can contain pressure, gauge,
% or constraint singular directions with exactly zero interface motion.
% Ranking a finite number of global singular vectors therefore does not
% reliably locate an interfacial mode.  Instead solve
%
%   min_q ||A_s q||^2 + w^2 |c'*q-1|^2 + alpha ||q||^2,
%
% where A_s is A scaled by its operator norm and c is the requested
% interface/Floquet seed.  Directions with c'*q=0 cannot satisfy the
% branch constraint.  All bulk, wall, interface, pressure, volume, and
% contact-line rows remain in A_s and are solved simultaneously.

A = block.A;
Bslow = block.Bslow;

if numel(seed) ~= size(A, 2)
    error('wnl_compute_mode:DirectSeedSize', ...
        'Mode-tracking seed has %d entries; the operator requires %d.', ...
        numel(seed), size(A, 2));
end
seed = seed(:);
seedNorm = norm(seed);
if seedNorm <= eps
    error('wnl_compute_mode:ZeroDirectSeed', ...
        'The mode-tracking seed is zero.');
end
seed = seed/seedNorm;

validateattributes(opts.modeTrackingConstraintWeight, {'numeric'}, ...
    {'scalar', 'real', 'positive', 'finite'});
validateattributes(opts.modeTrackingRegularization, {'numeric'}, ...
    {'scalar', 'real', 'nonnegative', 'finite'});
validateattributes(opts.modeTrackingSolveTolerance, {'numeric'}, ...
    {'scalar', 'real', 'positive', 'finite'});
validateattributes(opts.modeTrackingMaxIterations, {'numeric'}, ...
    {'scalar', 'real', 'integer', 'positive'});

[equilibratedA, rowScale] = equilibrate_rows(A);
numberOfUnknowns = size(A, 2);
weight = opts.modeTrackingConstraintWeight;
regularization = opts.modeTrackingRegularization;
augmentedA = [equilibratedA; weight*seed'; ...
    sqrt(regularization)*speye(numberOfUnknowns)];
augmentedRightHandSide = [zeros(size(A, 1), 1); weight; ...
    zeros(numberOfUnknowns, 1)];
[augmentedA, columnScale] = equilibrate_columns(augmentedA);

[scaledVector, flag, relativeResidual, iterations] = lsqr( ...
    augmentedA, augmentedRightHandSide, ...
    opts.modeTrackingSolveTolerance, opts.modeTrackingMaxIterations);
vector = columnScale.*scaledVector;
constraintBeforeNormalization = seed'*vector;
if abs(constraintBeforeNormalization) < ...
        opts.modeTrackingMinimumConstraint
    error('wnl_compute_mode:ConstrainedModeTrackingFailed', ...
        ['The full residual reconstruction could not create a mode with ', ...
         'nonzero interface-seed projection. Verify m, radialIndex, s, ', ...
         'N, and the contact-line condition. LSQR flag=%d, relres=%.3e.'], ...
        flag, relativeResidual);
end
vector = vector/constraintBeforeNormalization;

[scaledResidual,residualDetails] = wnl_descriptor_residual( ...
    A,Bslow,vector,'direct');
sigma = residualDetails.effectiveResidual;
operatorScale = residualDetails.operatorScale;
information = struct();
information.method = 'interface-constrained full residual';
information.operatorScale = operatorScale;
information.effectiveSingularValue = sigma;
information.scaledResidual = scaledResidual;
information.constraintBeforeNormalization = ...
    constraintBeforeNormalization;
information.constraintAfterNormalization = seed'*vector;
information.constraintWeight = weight;
information.regularization = regularization;
information.flag = flag;
information.relativeResidual = relativeResidual;
information.iterations = iterations;
information.restarts = 0;
information.numberOfAttempts = 1;
information.selectedAttempt = 1;
information.rowScaleRange = positive_range(rowScale);
information.columnScaleRange = positive_range(columnScale);
information.residualDetails = residualDetails;

if flag ~= 0 && opts.verbose
    warning('wnl_compute_mode:ConstrainedSolveNotConverged', ...
        ['The interface-constrained LSQR solve returned flag %d after ', ...
         '%d iterations (relres %.3e). Check the reported full-state ', ...
         'residual before using nonlinear coefficients.'], ...
        flag, iterations, relativeResidual);
end
end

function [vector, sigma, information] = ...
        reconstruct_from_prescribed_dofs(block, seed, spec, opts)
%RECONSTRUCT_FROM_PRESCRIBED_DOFS Lift a reduced interface null vector.
%
% For a free-contact-line Bessel branch, the reduced linear calculation
% already supplies every zeta(r,n).  Hold those interface coefficients
% fixed and solve every row of the full primitive operator for both-layer
% velocity and pressure.  This is the residual-consistent reconstruction
% of the Schur-complement interface mode.

A = block.A;
Bslow = block.Bslow;

localDofs = unique(spec.prescribedDofs(:));
if any(localDofs < 1) || any(localDofs > spec.ndof) || ...
        any(localDofs ~= round(localDofs))
    error('wnl_compute_mode:PrescribedDofs', ...
        'spec.prescribedDofs must contain valid local integer indices.');
end
numberOfHarmonics = numel(spec.n);
offsets = (0:numberOfHarmonics-1)*spec.ndof;
prescribed = reshape(localDofs+offsets, [], 1);
if numel(seed) ~= size(A, 2)
    error('wnl_compute_mode:DirectSeedSize', ...
        'Mode seed has %d entries; the operator requires %d.', ...
        numel(seed), size(A, 2));
end
prescribedValues = seed(prescribed);
if norm(prescribedValues) <= eps
    error('wnl_compute_mode:ZeroPrescribedSeed', ...
        'The prescribed interface portion of the mode seed is zero.');
end
prescribedValues = prescribedValues/norm(prescribedValues);

isFree = true(size(A, 2), 1);
isFree(prescribed) = false;
freeDofs = find(isFree);
reconstructionA = A(:, freeDofs);
reconstructionRightHandSide = ...
    -A(:, prescribed)*prescribedValues;
[scaledA, scaledRightHandSide, rowScale] = ...
    equilibrate_equations(reconstructionA, ...
    reconstructionRightHandSide);

regularization = opts.modeTrackingRegularization;
numberOfFreeDofs = numel(freeDofs);
augmentedA = [scaledA; ...
    sqrt(regularization)*speye(numberOfFreeDofs)];
augmentedRightHandSide = [scaledRightHandSide; ...
    zeros(numberOfFreeDofs, 1)];
[augmentedA, columnScale] = equilibrate_columns(augmentedA);
validateattributes(opts.directLiftMaxRestarts, {'numeric'}, ...
    {'scalar', 'integer', 'nonnegative'});
validateattributes(opts.directLiftSeedResidualTolerance,{'numeric'}, ...
    {'scalar','real','positive','finite'});
scaledFreeValues = complex(zeros(numberOfFreeDofs, 1));
warmStartUsed = false;
warmStartResidual = NaN;
warmStartSigma = Inf;
warmStartResidualDetails = struct();
if isfield(spec,'directLiftInitialVector') && ...
        ~isempty(spec.directLiftInitialVector)
    warmVector = spec.directLiftInitialVector(:);
    if numel(warmVector) ~= size(A,2) || ...
            any(~isfinite(real(warmVector))) || ...
            any(~isfinite(imag(warmVector)))
        error('wnl_compute_mode:DirectLiftWarmStart', ...
            ['The recovery warm-start vector must be finite and have ', ...
             'the same length as the full Floquet state.']);
    end
    warmPrescribed = warmVector(prescribed);
    warmDenominator = warmPrescribed'*warmPrescribed;
    if isfinite(real(warmDenominator)) && ...
            isfinite(imag(warmDenominator)) && ...
            abs(warmDenominator) > eps
        % Align the cached state to the current reduced-interface phase and
        % scale, then impose the current prescribed values exactly.
        warmScale = (warmPrescribed'*prescribedValues)/warmDenominator;
        warmVector = warmScale*warmVector;
        warmVector(prescribed) = prescribedValues;
        scaledFreeValues = warmVector(freeDofs)./columnScale;
        warmStartUsed = true;
        [warmStartResidual,warmStartResidualDetails] = ...
            wnl_descriptor_residual(A,Bslow,warmVector,'direct');
        warmStartSigma = warmStartResidualDetails.effectiveResidual;
    end
end
maximumAttempts = opts.directLiftMaxRestarts+1;
attemptFlags = nan(maximumAttempts, 1);
attemptRelativeResiduals = nan(maximumAttempts, 1);
attemptIterations = nan(maximumAttempts, 1);
attemptCumulativeIterations = nan(maximumAttempts, 1);
attemptEffectiveSingularValues = nan(maximumAttempts, 1);
attemptScaledResiduals = nan(maximumAttempts, 1);
attemptPhysicalStateNorms = nan(maximumAttempts, 1);
attemptFullStateNorms = nan(maximumAttempts, 1);
attemptAlgebraicInflationFactors = nan(maximumAttempts, 1);
bestScaledResidual = Inf;
bestEffectiveSingularValue = Inf;
bestVector = [];
bestFlag = NaN;
bestRelativeResidual = NaN;
bestAttemptIndex = NaN;
if warmStartUsed
    bestScaledResidual = warmStartResidual;
    bestEffectiveSingularValue = warmStartSigma;
    bestVector = warmVector;
    bestAttemptIndex = 0;
end
totalIterations = 0;
numberOfAttempts = 0;
liftResidualTarget = opts.modeResidualTolerance;
if opts.refineOperatingPointEigenpair && ...
        abs(wnl_spec_lambda(spec)) > 1.0e-13
    liftResidualTarget = max(liftResidualTarget, ...
        opts.directLiftSeedResidualTolerance);
end

for attemptIndex = 1:maximumAttempts
    [candidate, flag, relativeResidual, iterationsThisAttempt] = lsqr( ...
        augmentedA, augmentedRightHandSide, ...
        opts.modeTrackingSolveTolerance, ...
        opts.modeTrackingMaxIterations, [], [], scaledFreeValues);
    numberOfAttempts = attemptIndex;
    totalIterations = totalIterations+iterationsThisAttempt;

    candidateVector = complex(zeros(size(A, 2), 1));
    candidateVector(prescribed) = prescribedValues;
    candidateVector(freeDofs) = columnScale.*candidate;
    [candidateScaledResidual,candidateResidualDetails] = ...
        wnl_descriptor_residual(A,Bslow,candidateVector,'direct');
    candidateSigma = candidateResidualDetails.effectiveResidual;
    operatorScale = candidateResidualDetails.operatorScale;

    attemptFlags(attemptIndex) = flag;
    attemptRelativeResiduals(attemptIndex) = relativeResidual;
    attemptIterations(attemptIndex) = iterationsThisAttempt;
    attemptCumulativeIterations(attemptIndex) = totalIterations;
    attemptEffectiveSingularValues(attemptIndex) = candidateSigma;
    attemptScaledResiduals(attemptIndex) = candidateScaledResidual;
    attemptPhysicalStateNorms(attemptIndex) = ...
        candidateResidualDetails.physicalVectorNorm;
    attemptFullStateNorms(attemptIndex) = ...
        candidateResidualDetails.fullVectorNorm;
    attemptAlgebraicInflationFactors(attemptIndex) = ...
        candidateResidualDetails.fullToPhysicalNormRatio;

    % LSQR minimizes the equilibrated, regularized augmented equations.
    % That objective need not decrease the physical residual ||A*q|| used
    % by the WNL convergence gate. Checkpoint the best physical candidate
    % so a later restart cannot replace a more neutral reconstructed mode
    % by a worse augmented least-squares iterate.
    if isempty(bestVector) || (isfinite(candidateScaledResidual) && ...
            (~isfinite(bestScaledResidual) || ...
            candidateScaledResidual < bestScaledResidual))
        bestScaledResidual = candidateScaledResidual;
        bestEffectiveSingularValue = candidateSigma;
        bestVector = candidateVector;
        bestFlag = flag;
        bestRelativeResidual = relativeResidual;
        bestAttemptIndex = attemptIndex;
    end

    scaledFreeValues = candidate;
    if candidateScaledResidual <= liftResidualTarget || flag == 0
        break;
    end
end

attemptFlags = attemptFlags(1:numberOfAttempts);
attemptRelativeResiduals = ...
    attemptRelativeResiduals(1:numberOfAttempts);
attemptIterations = attemptIterations(1:numberOfAttempts);
attemptCumulativeIterations = ...
    attemptCumulativeIterations(1:numberOfAttempts);
attemptEffectiveSingularValues = ...
    attemptEffectiveSingularValues(1:numberOfAttempts);
attemptScaledResiduals = attemptScaledResiduals(1:numberOfAttempts);
attemptPhysicalStateNorms = ...
    attemptPhysicalStateNorms(1:numberOfAttempts);
attemptFullStateNorms = attemptFullStateNorms(1:numberOfAttempts);
attemptAlgebraicInflationFactors = ...
    attemptAlgebraicInflationFactors(1:numberOfAttempts);

vector = bestVector;
sigma = bestEffectiveSingularValue;
scaledResidual = bestScaledResidual;
restarts = numberOfAttempts-1;
[~,selectedResidualDetails] = wnl_descriptor_residual( ...
    A,Bslow,vector,'direct');

information = struct();
information.method = 'prescribed-interface full-state lift';
information.operatorScale = operatorScale;
information.effectiveSingularValue = sigma;
information.scaledResidual = scaledResidual;
information.flag = bestFlag;
information.relativeResidual = bestRelativeResidual;
information.iterations = totalIterations;
information.restarts = restarts;
information.numberOfAttempts = numberOfAttempts;
information.selectedAttempt = bestAttemptIndex;
information.selectedAttemptIndex = bestAttemptIndex;
if bestAttemptIndex == 0
    information.selectedCumulativeIterations = 0;
else
    information.selectedCumulativeIterations = ...
        attemptCumulativeIterations(bestAttemptIndex);
end
information.lastFlag = attemptFlags(end);
information.lastRelativeResidual = attemptRelativeResiduals(end);
information.attemptFlags = attemptFlags;
information.attemptRelativeResiduals = attemptRelativeResiduals;
information.attemptIterations = attemptIterations;
information.attemptCumulativeIterations = attemptCumulativeIterations;
information.attemptEffectiveSingularValues = ...
    attemptEffectiveSingularValues;
information.attemptScaledResiduals = attemptScaledResiduals;
information.attemptPhysicalStateNorms = attemptPhysicalStateNorms;
information.attemptFullStateNorms = attemptFullStateNorms;
information.attemptAlgebraicInflationFactors = ...
    attemptAlgebraicInflationFactors;
information.numberOfPrescribedDofs = numel(prescribed);
information.seedResidualTolerance = liftResidualTarget;
information.finalLinearResidualTolerance = opts.modeResidualTolerance;
information.acceptedAsRefinementSeed = scaledResidual <= ...
    liftResidualTarget && scaledResidual > opts.modeResidualTolerance;
information.rowScaleRange = positive_range(rowScale);
information.columnScaleRange = positive_range(columnScale);
information.residualDetails = selectedResidualDetails;
information.warmStartUsed = warmStartUsed;
information.warmStartResidual = warmStartResidual;
information.selectedFromWarmStart = bestAttemptIndex == 0;
information.warmStartResidualDetails = warmStartResidualDetails;
if isfield(spec,'recoveryWarmStartFile')
    information.warmStartFile = spec.recoveryWarmStartFile;
else
    information.warmStartFile = '';
end

if (~isfinite(scaledResidual) || ...
        scaledResidual > liftResidualTarget) && opts.verbose
    warning('wnl_compute_mode:InterfaceLiftNotConverged', ...
        ['The best prescribed-interface LSQR candidate has physical ', ...
         'scaled residual %.3e after %d total iterations and %d ', ...
         'restarts; the required tolerance is %.3e. Attempt %d of %d ', ...
         'was retained (selected flag %d, last flag %d). The final mode ', ...
         'residual gates will prevent nonlinear coefficients if ', ...
         'the subsequent full-eigenpair correction remains inaccurate.'], ...
        scaledResidual, totalIterations, restarts, ...
        liftResidualTarget, bestAttemptIndex, ...
        numberOfAttempts, bestFlag, attemptFlags(end));
elseif information.acceptedAsRefinementSeed && opts.verbose
    fprintf(['WNL prescribed-interface lift accepted as a Newton seed: ', ...
        'residual %.3e <= seed tolerance %.3e. Final linear/coefficient ', ...
        'gates remain %.3e/%.3e.\n'],scaledResidual, ...
        liftResidualTarget,opts.modeResidualTolerance, ...
        opts.coefficientModeResidualTolerance);
end
end

function [scaledA, rowScale] = equilibrate_rows(A)
[scaledA, ~, rowScale] = equilibrate_equations( ...
    A, complex(zeros(size(A, 1), 1)));
end

function [scaledA, scaledB, rowScale] = equilibrate_equations(A, b)
rowNorm = sqrt(full(sum(abs(A).^2, 2)));
largest = max(rowNorm);
if isempty(largest) || largest <= eps
    rowScale = ones(size(rowNorm));
else
    floorValue = max(largest*1.0e-12, eps);
    rowScale = ones(size(rowNorm));
    positive = rowNorm > 0;
    rowScale(positive) = 1./max(rowNorm(positive), floorValue);
end
scaledA = spdiags(rowScale, 0, size(A, 1), size(A, 1))*A;
scaledB = rowScale.*b;
end

function [scaledA, columnScale] = equilibrate_columns(A)
columnNorm = sqrt(full(sum(abs(A).^2, 1))).';
largest = max(columnNorm);
if isempty(largest) || largest <= eps
    columnScale = ones(size(columnNorm));
else
    floorValue = max(largest*1.0e-12, eps);
    columnScale = 1./max(columnNorm, floorValue);
end
scaledA = A*spdiags(columnScale, 0, size(A, 2), size(A, 2));
end

function scale = deterministic_matrix_scale(A)
% Upper bound for ||A||_2 without an iterative norm estimate.
oneNorm = norm(A, 1);
infinityNorm = norm(A, inf);
scale = max(sqrt(max(oneNorm, 0)*max(infinityNorm, 0)), eps);
end

function range = positive_range(values)
positive = values(isfinite(values) & values > 0);
if isempty(positive)
    range = [NaN, NaN];
else
    range = [min(positive), max(positive)];
end
end

function validate_block(block, spec)
required = {'A', 'Bslow'};
for j = 1:numel(required)
    if ~isfield(block, required{j})
        error('wnl_compute_mode:MissingBlockField', ...
            'model.block(%s) did not return block.%s.', ...
            spec.label, required{j});
    end
end
n = spec.ndof * numel(spec.n);
if ~isequal(size(block.A), [n, n])
    error('wnl_compute_mode:BadA', ...
        'block.A must have size [%d,%d].', n, n);
end
if ~isequal(size(block.Bslow), [n, n])
    error('wnl_compute_mode:BadBslow', ...
        'block.Bslow must have size [%d,%d].', n, n);
end
end

function [u, sigma, v] = smallest_svd(A, opts)
n = max(size(A));
if n <= opts.fullSvdMax
    [uAll, sAll, vAll] = svd(full(A), 'econ');
    singularValues = diag(sAll);
    [sigma, idx] = min(singularValues);
    u = uAll(:, idx);
    v = vAll(:, idx);
    return;
end

try
    [u, s, v] = svds(A, 1, 'smallest');
    sigma = s(1, 1);
catch
    [u, s, v] = svds(A, 1, 0);
    sigma = s(1, 1);
end
end
