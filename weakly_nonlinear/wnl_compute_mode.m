    opts.eigenpairReferenceMismatchMaximumLastStepRatio,{'numeric'}, ...
    {'scalar','real','positive','<=',1,'finite'});
if ~isempty(opts.eigenpairReferenceLambda)
    validateattributes(opts.eigenpairReferenceLambda,{'numeric'}, ...
        {'scalar','finite'});
end
validateattributes(opts.eigenpairPriorAcceptedSteps,{'numeric'}, ...
    {'scalar','integer','nonnegative'});
end

