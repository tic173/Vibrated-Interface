                    '(linear minus WNL)\n']);
                fprintf(['  Delta(a/g0)       linear growth', ...
                    '         WNL growth         difference\n']);
                for sweepIndex = 1:numel(accelerationOffsetSweep)
                    fprintf('  %12.5e  %18.10e  %18.10e  %18.10e\n', ...
                        accelerationOffsetSweep(sweepIndex), ...
                        exactLinearGrowthSweep(sweepIndex), ...
                        wnlGrowthSweep(sweepIndex), ...
                        growthRateDifferenceSweepLinearMinusWnl( ...
                        sweepIndex));
                end
            end

            if useSmallAmplitudeTransient
                comparisonFigureName = ...
                    'Linear versus small-amplitude cubic correction';
            else
                comparisonFigureName = 'Linear versus weakly nonlinear';
            end
            if comparisonIsExploratory
                comparisonFigureName = sprintf( ...
                    'Linear versus exploratory %s',nonlinearModelLabel);
            end
            figure('Name', comparisonFigureName);
            tiledlayout(3, 1, 'TileSpacing', 'compact');

            nexttile;
            exactGrowthHandle = plot(accelerationOffsetSweep, ...
                exactLinearGrowthSweep, 'o-', 'LineWidth', 1.3);
            hold on;
            wnlGrowthHandle = plot(accelerationOffsetSweep, ...
                wnlGrowthSweep, '--', 'LineWidth', 1.4);
            zeroHandle = yline(0, ':');
            zeroHandle.HandleVisibility = 'off';
            grid on;
            xlabel('acceleration offset, \Delta a/g_0');
            ylabel('growth rate, Re(\gamma^*)');
            legend([exactGrowthHandle, wnlGrowthHandle], ...
                'exact linear Floquet', 'WNL tangent', ...
                'Location', 'best');
            title(sprintf('growth-sweep relative L_2 error = %.3g', ...
                growthSweepRelativeL2Error));

            nexttile;
            hold on;
            numberOfComparedModes = size(modeAmplitudesLinear,2);
            trajectoryColors = lines(numberOfComparedModes);
            trajectoryHandles = gobjects(2*numberOfComparedModes,1);
            trajectoryLabels = cell(2*numberOfComparedModes,1);
            for comparedModeIndex = 1:numberOfComparedModes
                trajectoryHandles(2*comparedModeIndex-1) = plot( ...
                    comparisonForcingPeriods, ...
                    realModeAmplitudesLinear(:,comparedModeIndex),'-', ...
                    'Color',trajectoryColors(comparedModeIndex,:), ...
                    'LineWidth',1.3);
                trajectoryHandles(2*comparedModeIndex) = plot( ...
                    comparisonForcingPeriods, ...
                    realModeAmplitudesWnl(:,comparedModeIndex),'--', ...
                    'Color',trajectoryColors(comparedModeIndex,:), ...
                    'LineWidth',1.5);
                trajectoryLabels{2*comparedModeIndex-1} = sprintf( ...
                    'linear Re(A_%d)',comparedModeIndex);
                trajectoryLabels{2*comparedModeIndex} = sprintf( ...
                    '%s Re(A_%d)',nonlinearModelLabel,comparedModeIndex);
            end
            zeroHandle = yline(0,':');
            zeroHandle.HandleVisibility = 'off';
            grid on;
            xlabel('forcing periods, t/T_f');
            ylabel('Re(A_j), \zeta/h');
            legend(trajectoryHandles,trajectoryLabels,'Location','best');
            title('signed modal trajectories');

            nexttile;
            plot(comparisonForcingPeriods, ...
                linearInterfaceSignal, ...
                'LineWidth', 1.1);
            hold on;
            plot(comparisonForcingPeriods, ...
                wnlInterfaceSignal, '--', 'LineWidth', 1.2);
            grid on;
            xlabel('forcing periods, t/T_f');
            ylabel('\zeta/h at probe');
            legend('linear Floquet', ...
                sprintf('%s including O(A^2)',nonlinearModelLabel), ...
                'Location', 'best');
            title(sprintf(['growth-rate relative error = %.3g, ', ...
                '\Delta a=%.3g'], growthRateRelativeError, ...
                accelerationOffset));

            if input.comparison.plotDifference
                figure('Name',sprintf('Linear minus %s differences', ...
                    nonlinearModelLabel));
                tiledlayout(3, 1, 'TileSpacing', 'compact');

                nexttile;
                plot(accelerationOffsetSweep, ...
                    growthRateDifferenceSweepLinearMinusWnl, 'o-', ...
                    'LineWidth', 1.3);
                hold on;
                zeroHandle = yline(0, ':');
                zeroHandle.HandleVisibility = 'off';
                grid on;
                xlabel('acceleration offset, \Delta a/g_0');
                ylabel('\Delta growth rate');
                title(sprintf(['growth-rate difference: linear - ', ...
                    'reduced tangent, RMSE = %.3g'],growthSweepRmse));

                nexttile;
                hold on;
                differenceHandles = gobjects(numberOfComparedModes,1);
                differenceLabels = cell(numberOfComparedModes,1);
                for comparedModeIndex = 1:numberOfComparedModes
                    differenceHandles(comparedModeIndex) = plot( ...
                        comparisonForcingPeriods, ...
                        realModeAmplitudeDifferenceLinearMinusWnl( ...
                        :,comparedModeIndex), ...
                        'Color',trajectoryColors(comparedModeIndex,:), ...
                        'LineWidth',1.3);
                    differenceLabels{comparedModeIndex} = sprintf( ...
                        'Re(A_%d^{lin}-A_%d^{cubic})', ...
                        comparedModeIndex,comparedModeIndex);
                end
                zeroHandle = yline(0, ':');
                zeroHandle.HandleVisibility = 'off';
                grid on;
                xlabel('forcing periods, t/T_f');
                ylabel('\Delta Re(A_j), \zeta/h');
                legend(differenceHandles,differenceLabels, ...
                    'Location','best');
                title(sprintf(['modal difference: linear - %s, max ', ...
                    'relative L_2 = %.3g'], ...
                    nonlinearModelLabel, ...
                    max(realModeAmplitudeRelativeL2Error)));

                nexttile;
                plot(comparisonForcingPeriods, real( ...
                    interfaceSignalDifferenceLinearMinusWnl), ...
                    'LineWidth', 1.1);
                hold on;
                zeroHandle = yline(0, ':');
                zeroHandle.HandleVisibility = 'off';
                grid on;
                xlabel('forcing periods, t/T_f');
                ylabel('Re(\Delta\zeta/h)');
                title(sprintf(['interface-signal difference: ', ...
                    'linear - %s, relative L_2 = %.3g'], ...
                    nonlinearModelLabel,interfaceSignalRelativeL2Error));
            end
            if useSmallAmplitudeTransient
                figure('Name','Small-amplitude validity diagnostics');
                tiledlayout(2,1,'TileSpacing','compact');
                nexttile;
                plot(comparisonForcingPeriods,relativeCubicCorrection, ...
                    'LineWidth',1.3);
                hold on;
                yline(input.comparison. ...
                    maximumRelativeCubicCorrection,':','limit');
                grid on;
                xlabel('forcing periods, t/T_f');
                ylabel('|\delta A_j^{(3)}|/|A_{L,j}|');
                legend(compose('mode %d',1:numberOfComparedModes), ...
                    'Location','best');
                title('accumulated cubic correction');

                nexttile;
                plot(comparisonForcingPeriods, ...
                    nonlinearToLinearRateRatio,'LineWidth',1.3);
                hold on;
                yline(input.comparison. ...
                    maximumNonlinearToLinearRateRatio,':','limit');
                grid on;
                xlabel('forcing periods, t/T_f');
                ylabel('|N_j(A_L)|/|\lambda_j A_{L,j}|');
                legend(compose('mode %d',1:numberOfComparedModes), ...
                    'Location','best');
                title('instantaneous nonlinear-to-linear rate ratio');
            end
        end
    end
end

