        forcingPeriods = timeStar/forcingPeriodStar;

        temporalPhases = exp(1i*harmonicIndices(:) * ...
            (p.omegaStar*timeStar));
        periodicUnscaled = zetaCoefficients.'*temporalPhases;
        firstPeriodIndices = 1:(input.linear.samplesPerPeriod+1);
        [periodicScale, peakIndex] = max(abs( ...
            periodicUnscaled(firstPeriodIndices)));
        if periodicScale <= eps*max(norm(zetaCoefficients), 1)
            error('vi_wnl_user_run:ZeroFloquetSignal', ...
                'The reconstructed Floquet interface signal is zero.');
        end
        phaseRotation = exp(-1i*angle(periodicUnscaled(peakIndex)));
        zetaCoefficientsNormalized = ...
            phaseRotation*zetaCoefficients/periodicScale;
        periodicPart = ...
            zetaCoefficientsNormalized.'*temporalPhases;

        initialAmplitude = initialConditions.amplitudesOverH(1);
        initialPhase = initialConditions.phases(1);
        floquetOscillation = ...
            exp(1i*imag(gammaStar)*timeStar).*periodicPart;
        displacementOverH = initialAmplitude * ...
            exp(1i*initialPhase) * ...
            exp(real(gammaStar)*timeStar).*floquetOscillation;
        growthEnvelope = initialAmplitude * ...
            exp(real(gammaStar)*timeStar);
        stroboscopicIndices = ...
            1:input.linear.samplesPerPeriod:numberOfSamples;

        gammaPhysical = gammaStar/timeScale;
        floquetMultiplier = exp(gammaStar*forcingPeriodStar);
        rawQuasifrequency = imag(gammaStar)/p.omegaStar;
        wrappedQuasifrequency = ...
            wnl_wrap_quasifrequency(rawQuasifrequency);

        linearResult.modeType = legacyModeType;
        linearResult.aCritical = p.aCritical;
        linearResult.aAnalysis = p.aAnalysis;
        linearResult.analysisAmplitude = p.aAnalysis;
        linearResult.analysisAmplitudeSource = ...
            analysisAmplitudeInfo.source;
        linearResult.accelerationOffsetFromCritical = ...
            analysisAmplitudeInfo.detuningFromCritical;
        linearResult.betaStar = p.modes(1).betaStar;
        linearResult.gammaStar = gammaStar;
        linearResult.gammaPhysical = gammaPhysical;
        linearResult.growthRateStar = real(gammaStar);
        linearResult.growthRatePerSecond = real(gammaPhysical);
        linearResult.angularFrequencyStar = imag(gammaStar);
        linearResult.angularFrequencyRadPerSecond = imag(gammaPhysical);
        linearResult.rawQuasifrequency = rawQuasifrequency;
        linearResult.wrappedQuasifrequency = wrappedQuasifrequency;
        linearResult.forcingPeriodStar = forcingPeriodStar;
        linearResult.forcingPeriodSeconds = forcingPeriodStar*timeScale;
        linearResult.floquetMultiplier = floquetMultiplier;
        linearResult.multiplierMagnitude = abs(floquetMultiplier);
        linearResult.harmonicIndices = harmonicIndices;
        linearResult.zetaCoefficients = zetaCoefficients;
        linearResult.zetaCoefficientsNormalized = ...
            zetaCoefficientsNormalized;
        linearResult.neutralExponent = neutralExponent;
        linearResult.neutralZetaCoefficients = neutralZetaCoefficients;
        linearResult.neutralModeDiagnostics = neutralModeDiagnostics;
        linearResult.timeStar = timeStar;
        linearResult.timeSeconds = timeStar*timeScale;
        linearResult.forcingPeriods = forcingPeriods;
        linearResult.periodicPart = periodicPart;
        linearResult.floquetOscillation = floquetOscillation;
        linearResult.displacementOverH = displacementOverH;
        linearResult.growthEnvelope = growthEnvelope;
        linearResult.stroboscopicIndices = stroboscopicIndices;
        linearResult.rootSearch = rootSearchResult;

        fprintf('\nLinear Floquet result for the first mode\n');
        fprintf('  mode type                  = %s\n', legacyModeType);
        fprintf('  critical acceleration     = %.12g g0\n', p.aCritical);
        fprintf('  analyzed acceleration     = %.12g g0\n', p.aAnalysis);
        fprintf('  gammaStar                  = %.12g%+.12gi\n', ...
            real(gammaStar), imag(gammaStar));
        fprintf('  growth rate               = %.12g [1/tStar]\n', ...
            real(gammaStar));
        fprintf('  physical growth rate      = %.12g [1/s]\n', ...
            real(gammaPhysical));
        fprintf('  wrapped quasifrequency s  = %.12g\n', ...
            wrappedQuasifrequency);
        fprintf('  Floquet multiplier        = %.12g%+.12gi\n', ...
            real(floquetMultiplier), imag(floquetMultiplier));
        fprintf('  multiplier magnitude      = %.12g\n\n', ...
            abs(floquetMultiplier));

        if input.run.plotLinearTransient
            figure('Name', 'Linear Floquet transient');
            tiledlayout(4, 1, 'TileSpacing', 'compact');

            nexttile;
            floquetPlotEnd = min(2*input.linear.samplesPerPeriod+1, ...
                numberOfSamples);
            plot(forcingPeriods(1:floquetPlotEnd), ...
                real(floquetOscillation(1:floquetPlotEnd)), ...
                'LineWidth', 1.3);
            grid on;
            xlabel('forcing periods, t/T_f');
            ylabel('Re(\Phi_F)');
            title('Unit-envelope Floquet dynamics');

            nexttile;
            plot(forcingPeriods, real(displacementOverH), ...
                'LineWidth', 1.3);
            hold on;
            plot(forcingPeriods(stroboscopicIndices), ...
                real(displacementOverH(stroboscopicIndices)), ...
                'o', 'MarkerSize', 4);
            grid on;
            xlabel('forcing periods, t/T_f');
            ylabel('Re(\zeta/h)');
            legend('continuous', 'stroboscopic', 'Location', 'best');
            title(sprintf(['m=%d, l=%d, a/g_0=%.5g, ', ...
                'Re(\\gamma^*)=%.4g'], target.m, ...
                target.radialIndex, p.aAnalysis, real(gammaStar)), ...
                'Interpreter', 'tex');

            nexttile;
            semilogy(forcingPeriods, ...
                max(abs(displacementOverH), realmin), ...
                'LineWidth', 1.2);
            hold on;
            semilogy(forcingPeriods, growthEnvelope, '--', ...
                'LineWidth', 1.3);
            grid on;
            xlabel('forcing periods, t/T_f');
            ylabel('modal magnitude');
            legend('|\zeta/h|', 'exp[Re(\gamma^*)t^*] envelope', ...
                'Location', 'best');

            nexttile;
            stem(harmonicIndices+wrappedQuasifrequency, ...
                abs(zetaCoefficientsNormalized), 'filled');
            grid on;
            xlabel('temporal frequency index, n+s');
            ylabel('|\zeta_n|');
            title('Floquet harmonic content');
        end
    end
end

%% Full weakly nonlinear calculation
wnlResult = [];
wnlFailure = struct();
operatorMetadata = struct();
recoveryCache = struct('requested',false,'used',false,'valid',false, ...
    'warmStarted',false,'file','','reason','not requested');
operatingPointModes = cell(numel(input.modes), 1);
slowEnvelopeRatios = zeros(numel(input.modes),1);
slowEnvelopeValid = true;
slowModeSelection = struct();
autoSelectedModes = false;
if input.run.weaklyNonlinear
    if exist(input.run.operatorFactory, 'file') == 0
        error('vi_wnl_user_run:MissingOperatorFactory', ...
            ['Cannot find %s.m.  It must return [operators,metadata], ', ...
             'where metadata.ndof is defined and operators supplies ', ...
             'B0, Lhat, C, D, and optionally P as documented in ', ...
             'weakly_nonlinear/vi_wnl_model.m.'], ...
            input.run.operatorFactory);
    end

    if ~isfield(p, 'aAnalysis')
        [p.aAnalysis, analysisAmplitudeInfo] = ...
            vi_resolve_analysis_amplitude( ...
            input.forcing, input.linear, p.aCritical);
    end

    operatorParameters = p;
    operatorParameters.execution = input.execution;
    if useOperatingPointWnl
        fprintf(['\nOperating-point WNL reference: a/g0 = ', ...
            '%.12g\n'], p.aAnalysis);
        rootOptions = input.linear.rootSearch;
        for operatingModeIndex = 1:numel(input.modes)
            precomputedRoot = [];
            if operatingModeIndex == 1 && ...
                    isfield(linearResult, 'rootSearch') && ...
                    isstruct(linearResult.rootSearch) && ...
                    isfield(linearResult.rootSearch, 'gammaCanonical')
                precomputedRoot = linearResult.rootSearch;
            end
            operatingPointModes{operatingModeIndex} = ...
                vi_operating_point_floquet_mode( ...
                p, input.modes(operatingModeIndex), ...
                input.numerics.N, rootOptions, precomputedRoot);
            operatingMode = ...
                operatingPointModes{operatingModeIndex};
            fprintf(['  %-24s lambda = %.12g%+.12gi, ', ...
                's = %.12g, reduced residual = %.3e\n'], ...
                operatingMode.label, real(operatingMode.lambda), ...
                imag(operatingMode.lambda), operatingMode.s, ...
                operatingMode.diagnostics.vectorResidual);
            slowRateRatio = abs(real(operatingMode.lambda)) / ...
                max(p.omegaStar, eps);
            operatingPointModes{operatingModeIndex}.slowRateRatio = ...
                slowRateRatio;
            slowEnvelopeRatios(operatingModeIndex) = slowRateRatio;
            slowEnvelopeValid = slowEnvelopeValid && ...
                slowRateRatio <= ...
                input.weaklyNonlinear.maximumSlowRateRatio;
            if slowRateRatio > ...
                    input.weaklyNonlinear.maximumSlowRateRatio
                if useSmallAmplitudeTransient
                    warning('vi_wnl_user_run:FastOperatingMode', ...
                        ['Mode %s has |Re(lambda)|/omegaStar=%.3g, above ', ...
                         'the slow-envelope ratio %.3g. The selected ', ...
                         'finite-time O(A^3) correction does not assume ', ...
                         'a slow envelope; it will instead stop at the ', ...
                         'configured perturbative correction limits.'], ...
                        operatingMode.label,slowRateRatio, ...
                        input.weaklyNonlinear.maximumSlowRateRatio);
                else
                    warning('vi_wnl_user_run:FastOperatingMode', ...
                        ['Mode %s has |Re(lambda)|/omegaStar=%.3g, above ', ...
                         'the requested slow-envelope warning ratio %.3g. ', ...
                         'The exact linear exponent is valid, but a cubic ', ...
                         'amplitude truncation may not be quantitative.'], ...
                        operatingMode.label,slowRateRatio, ...
                        input.weaklyNonlinear.maximumSlowRateRatio);
                end
            end
        end
        if ~slowEnvelopeValid && ...
                input.weaklyNonlinear.autoSelectSlowModes && ...
                numel(input.modes) > 1
            searchOptions = input.weaklyNonlinear.slowModeSearch;
            searchOptions.maximumSlowRateRatio = ...
                input.weaklyNonlinear.maximumSlowRateRatio;
            searchOptions.autoSelectionAllowsModeRecovery = ...
                input.weaklyNonlinear.autoSelectionAllowsModeRecovery;
            searchOptions.precomputedOperatingModes = operatingPointModes;
            [selectedModes, selectedOperatingModes, ...
                slowModeSelection] = vi_select_slow_operating_modes( ...
                p, input.modes, input.numberOfModes, ...
                input.numerics.N, rootOptions, searchOptions);
            if slowModeSelection.success && slowModeSelection.changed
                fprintf(['  auto-selected slow two-mode set; replacing ', ...
                    'the fast retained branch before full WNL recovery.\n']);
                input.requestedModesBeforeAutoSelection = input.modes;
                input.modes = selectedModes;
                p.modes = input.modes;
                operatingPointModes = selectedOperatingModes(:);
                slowEnvelopeRatios = cellfun(@(mode) ...
                    mode.slowRateRatio, operatingPointModes(:));
                slowEnvelopeValid = all(slowEnvelopeRatios <= ...
                    input.weaklyNonlinear.maximumSlowRateRatio);
                for selectedModeIndex = 1:numel(input.modes)
                    selectedRoot = bessel_derivative_root( ...
                        input.modes(selectedModeIndex).m, ...
                        input.modes(selectedModeIndex).radialIndex);
                    p.modes(selectedModeIndex).betaStar = ...
                        selectedRoot( ...
                        input.modes(selectedModeIndex).radialIndex) / ...
                        p.R0;
                    fprintf(['    retained mode %d: m=%d, l=%d, ', ...
                        's=%.10g, betaStar=%.10g, ', ...
                        '|Re(lambda)|/omegaStar=%.4g\n'], ...
                        selectedModeIndex, ...
                        input.modes(selectedModeIndex).m, ...
                        input.modes(selectedModeIndex).radialIndex, ...
                        wnl_wrap_quasifrequency( ...
                        input.modes(selectedModeIndex).s), ...
                        p.modes(selectedModeIndex).betaStar, ...
                        slowEnvelopeRatios(selectedModeIndex));
                end
                initialConditions = vi_mode_initial_conditions( ...
                    input.modes, input.initialConditions);
                autoSelectedModes = true;
                if input.weaklyNonlinear.autoSelectionAllowsModeRecovery
                    input.run.allowModeRecoveryDuringCoefficientRun = true;
                    fprintf(['  auto-selected modes invalidate old ', ...
                        'recovery caches; mode recovery during this ', ...
                        'coefficient run is now allowed.\n']);
                end
            elseif slowModeSelection.success
                operatingPointModes = selectedOperatingModes(:);
                slowEnvelopeRatios = cellfun(@(mode) ...
                    mode.slowRateRatio, operatingPointModes(:));
                slowEnvelopeValid = all(slowEnvelopeRatios <= ...
                    input.weaklyNonlinear.maximumSlowRateRatio);
            else
                warning('vi_wnl_user_run:SlowModeAutoSelectionFailed', ...
                    ['Automatic slow-mode selection did not find a ', ...
                     'valid retained set: %s'], slowModeSelection.reason);
            end
        end
        % The factory names the forcing amplitude aCritical for historical
        % reasons. At an operating point it must receive the actual requested
        % acceleration so B0/Lhat/C/D/P all describe the same physical state.
        operatorParameters.aCritical = p.aAnalysis;
        operatorParameters.operatingAmplitude = p.aAnalysis;
    else
        fprintf(['\nCommon-neutral WNL reference: a_c/g0 = ', ...
            '%.12g\n'], p.aCritical);
    end

    factory = str2func(input.run.operatorFactory);
    [operators, operatorMetadata] = factory(operatorParameters);
    assert(isfield(operatorMetadata, 'ndof'), ...
        'The operator factory must return metadata.ndof.');
    fprintf('\nFull-cylinder WNL discretization\n');
    if isfield(operatorMetadata, 'contactLine')
        fprintf('  contact line               = %s\n', ...
            operatorMetadata.contactLine);
    end
    fprintf('  Nr, NzLower, NzUpper       = %d, %d, %d\n', ...
        operatorMetadata.layout.nr, operatorMetadata.layout.nzD, ...
        operatorMetadata.layout.nzL);
    if isfield(operatorMetadata, 'radialGrid')
        fprintf('  radial differentiation     = %s\n', ...
            operatorMetadata.radialGrid.typeUsed);
        if strcmp(operatorMetadata.radialGrid.typeUsed, ...
                'besselEnriched')
            fprintf('  radial basis condition     = %.6e\n', ...
                operatorMetadata.radialGrid.conditionNumber);
        end
    end
    if isfield(operatorMetadata, 'verticalGrid')
        fprintf('  lower/upper z elements     = %d / %d\n', ...
            operatorMetadata.verticalGrid.lower.numberOfElements, ...
            operatorMetadata.verticalGrid.upper.numberOfElements);
    end
    fprintf('  unknowns per harmonic      = %d\n', ...
        operatorMetadata.ndof);

    config.omega = p.omegaStar;
    config.N = input.numerics.N;
    config.ndof = operatorMetadata.ndof;
    model = vi_wnl_model(config, operators);
    % Enables row-family diagnostics for any unconverged nonlinear forced
    % field without making the generic WNL solver cylinder-specific.
    model.residualLayout = operatorMetadata;

    specs = cell(numel(input.modes), 1);
    for j = 1:numel(input.modes)
        selected = input.modes(j);
        specS = selected.s;
        if useOperatingPointWnl
            specS = operatingPointModes{j}.s;
        end
        specs{j} = model.makeSpec(selected.m, specS, selected.label);
        if useOperatingPointWnl
            specs{j}.lambda = operatingPointModes{j}.lambda;
            specs{j}.reducedReferenceLambda = ...
                operatingPointModes{j}.lambda;
            specs{j}.operatingExponent = ...
                operatingPointModes{j}.gamma;
            specs{j}.referenceAmplitude = p.aAnalysis;
        end
        specs{j}.radialIndex = selected.radialIndex;
        specs{j}.betaStar = p.modes(j).betaStar;

        % Branch-tracking seed.  Its interface component identifies the
        % requested radial/Floquet branch; it is not used as the final
        % eigenvector. wnl_compute_mode reconstructs the complete state by
        % minimizing the full residual with a nonzero projection onto this
        % seed. The returned velocity, pressure, interface, wall, gauge,
        % volume, and contact-line equations all come from that operator.
        radialSeed = besselj(abs(selected.m), ...
            p.modes(j).betaStar*operatorMetadata.discretization.r);
        radialSeed = radialSeed/max(norm(radialSeed), eps);
        temporalSeed = complex(zeros(1, numel(specs{j}.n)));
        seedSource = 'central Floquet harmonic';
        hasReducedTemporalSeed = false;
        if useOperatingPointWnl
            reducedSeed = operatingPointModes{j}.zeta;
            reducedIndices = ...
                operatingPointModes{j}.harmonicIndices;
            reducedSeedDiagnostics = ...
                operatingPointModes{j}.diagnostics;
            hasReducedTemporalSeed = true;
            seedSource = ...
                'exact reduced Floquet vector at analysis amplitude';
        elseif j == 1 && isfield(linearResult, ...
                'neutralZetaCoefficients')
            reducedSeed = linearResult.neutralZetaCoefficients;
            reducedIndices = linearResult.harmonicIndices;
            reducedSeedDiagnostics = ...
                linearResult.neutralModeDiagnostics;
            hasReducedTemporalSeed = true;
        else
            selectedS = wnl_wrap_quasifrequency(selected.s);
            reducedType = '';
            if abs(selectedS) < 1e-12
                reducedType = 'H';
            elseif abs(selectedS-0.5) < 1e-12
                reducedType = 'SH';
            end
            if ~isempty(reducedType)
                [reducedSeed, reducedSeedDiagnostics] = ...
                    vi_reduced_cylinder_mode_at_exponent( ...
                    p.aCritical, p.omegaStar, p.R0, selected.m, ...
                    selected.radialIndex, p.C, p.Bd, p.At, p.eta, ...
                    input.numerics.N, reducedType, p.g_sgn, ...
                    1i*selectedS*p.omegaStar, p.phase);
                if strcmp(reducedType, 'SH')
                    reducedIndices = ...
                        -input.numerics.N-1:input.numerics.N;
                else
                    reducedIndices = ...
                        -input.numerics.N:input.numerics.N;
                end
                hasReducedTemporalSeed = true;
                fprintf(['  reduced neutral residual %-12s ', ...
                    '= %.6e\n'], selected.label, ...
                    reducedSeedDiagnostics.vectorResidual);
                if reducedSeedDiagnostics.vectorResidual > ...
                        input.options.modeResidualTolerance
                    warning('vi_wnl_user_run:AdditionalModeNotNeutral', ...
                        ['Mode %s is not neutral at the common expansion ', ...
                         'acceleration aCritical=%.12g: reduced residual ', ...
                         '%.3e. Two-mode WNL requires both modes to be ', ...
                         'neutral at this same point.'], selected.label, ...
                        p.aCritical, ...
                        reducedSeedDiagnostics.vectorResidual);
                end
            end
        end
        if hasReducedTemporalSeed
            for harmonicIndex = 1:numel(specs{j}.n)
                sourceIndex = find(reducedIndices == ...
                    specs{j}.n(harmonicIndex), 1);
                if ~isempty(sourceIndex)
                    temporalSeed(harmonicIndex) = ...
                        reducedSeed(sourceIndex);
                end
            end
            if ~useOperatingPointWnl
                seedSource = 'phase-matched reduced neutral vector';
            end
        else
            [~, centralIndex] = min(abs(specs{j}.n+specs{j}.s));
            temporalSeed(centralIndex) = 1;
        end
        if norm(temporalSeed) <= eps
            error('vi_wnl_user_run:ZeroModeTrackingSeed', ...
                ['The temporal mode-tracking seed for %s is zero. Check ', ...
                 'the reduced linear harmonic indices and WNL cutoff N.'], ...
                selected.label);
        end
        seedCoefficients = complex(zeros(operatorMetadata.ndof, ...
            numel(specs{j}.n)));
        seedCoefficients(operatorMetadata.layout.zeta, :) = ...
            radialSeed*temporalSeed;
        specs{j}.directSeed = seedCoefficients(:);
        specs{j}.directSeedSource = seedSource;
        if hasReducedTemporalSeed
            specs{j}.reducedModeDiagnostics = reducedSeedDiagnostics;
            if ~useOperatingPointWnl
                specs{j}.reducedNeutralDiagnostics = ...
                    reducedSeedDiagnostics;
            end
        end
        if strcmpi(input.boundary.contactLine, 'free') && ...
                hasReducedTemporalSeed
            % The reduced free-contact-line solve is the Schur complement
            % for these zeta coefficients. Hold them fixed while lifting
            % the complete velocity-pressure state from the full operator.
            specs{j}.prescribedDofs = operatorMetadata.layout.zeta;
        end
        fprintf('  mode-tracking seed %-12s = %s\n', ...
            selected.label, seedSource);

        % Optional mode seeds supplied by the factory.  Each cell must be a
        % full Floquet vector with ndof*numel(spec.n) entries.
        if isfield(operatorMetadata, 'direct') && ...
                numel(operatorMetadata.direct) >= j && ...
                ~isempty(operatorMetadata.direct{j})
            specs{j}.direct = operatorMetadata.direct{j};
        end
        if isfield(operatorMetadata, 'left') && ...
                numel(operatorMetadata.left) >= j && ...
                ~isempty(operatorMetadata.left{j})
            specs{j}.left = operatorMetadata.left{j};
        end
    end

    skipCoefficientRunForFastModes = useOperatingPointWnl && ...
        ~input.run.modeRecoveryOnly && input.run.compareLinearAndWNL && ...
        input.weaklyNonlinear.requireSlowModesForComparison && ...
        input.weaklyNonlinear.stopCoefficientRunWhenSlowEnvelopeFails && ...
        ~slowEnvelopeValid;

    if ~skipCoefficientRunForFastModes && input.run.reuseRecoveredModes
        [specs,recoveryCache] = vi_wnl_apply_recovery_cache( ...
            input.run.recoveredModeFile,repositoryRoot,input,p, ...
            specs,operatorMetadata.ndof);
        if recoveryCache.used
            fprintf(['  recovery cache accepted: %d mode(s) from %s ', ...
                '(release %s)\n'],recoveryCache.numberOfModes, ...
                recoveryCache.file,recoveryCache.sourceCodeRelease);
            fprintf(['  current blocks will recheck direct/adjoint ', ...
                'residuals, normalization, conjugates, and reduced/full ', ...
                'exponent agreement.\n']);
        elseif recoveryCache.warmStarted
            if input.run.requireRecoveredModes
                error('vi_wnl_user_run:RequiredRecoveryCacheRejected', ...
                    ['Required coefficient-ready cache was incomplete: ', ...
                     '%s'],recoveryCache.reason);
            end
            fprintf(['  incomplete recovery warm start accepted from ', ...
                '%s (%s).\n'],recoveryCache.file,recoveryCache.reason);
            if ~input.run.modeRecoveryOnly
                input.run.modeRecoveryOnly = true;
                fprintf(['  coefficient evaluation deferred for this ', ...
                    'run; resuming mode recovery from the saved ', ...
                    'full-state vectors.\n']);
            end
        elseif input.run.requireRecoveredModes
            error('vi_wnl_user_run:RequiredRecoveryCacheRejected', ...
                'Required recovered-mode cache was rejected: %s', ...
                recoveryCache.reason);
        elseif autoSelectedModes && ...
                input.weaklyNonlinear.autoSelectionAllowsModeRecovery
            fprintf(['  recovery cache not used after auto-selection: ', ...
                '%s. The newly selected modes will be reconstructed ', ...
                'normally.\n'],recoveryCache.reason);
        else
            fprintf(['  recovery cache not used: %s. The modes will ', ...
                'be reconstructed normally.\n'],recoveryCache.reason);
        end
    end
    if ~skipCoefficientRunForFastModes && ...
            ~input.run.modeRecoveryOnly && ~recoveryCache.used && ...
            ~input.run.allowModeRecoveryDuringCoefficientRun
        if ~input.run.reuseRecoveredModes
            cacheReason = 'input.run.reuseRecoveredModes is false';
        else
            cacheReason = recoveryCache.reason;
        end
        error('vi_wnl_user_run:CoefficientRunNeedsRecoveryCache', ...
            ['Coefficient evaluation was stopped before mode recovery. ', ...
             'No validated recovery cache was used (%s). Run once with ', ...
             'input.run.modeRecoveryOnly=true and save the result. Then ', ...
             'set modeRecoveryOnly=false and set recoveredModeFile to the ', ...
             'absolute Saved path printed by that run. To deliberately ', ...
             'recover and evaluate coefficients in one run, set ', ...
             'allowModeRecoveryDuringCoefficientRun=true.'],cacheReason);
    end

    opts = input.options;
    opts.detuning = input.detuning.direction;
    if isfield(operatorMetadata, 'normalizeDirect') && ...
            isa(operatorMetadata.normalizeDirect, 'function_handle')
        opts.normalizeDirect = operatorMetadata.normalizeDirect;
    end
    if skipCoefficientRunForFastModes
        failingModeMessages = {};
        for fastModeIndex = 1:numel(input.modes)
            if slowEnvelopeRatios(fastModeIndex) <= ...
                    input.weaklyNonlinear.maximumSlowRateRatio
                continue;
            end
            modeLabel = sprintf('mode %d',fastModeIndex);
            if isfield(input.modes(fastModeIndex),'label')
                modeLabel = input.modes(fastModeIndex).label;
            end
            if fastModeIndex <= numel(operatingPointModes) && ...
                    ~isempty(operatingPointModes{fastModeIndex}) && ...
                    isfield(operatingPointModes{fastModeIndex},'label')
                modeLabel = operatingPointModes{fastModeIndex}.label;
            end
            failingModeMessages{end+1} = sprintf( ...
                '%s: |Re(lambda)|/omegaStar=%.3g', ...
                modeLabel,slowEnvelopeRatios(fastModeIndex)); %#ok<SAGROW>
        end
        wnlFailure.available = false;
        wnlFailure.status = 'slow-envelope preflight failed';
        wnlFailure.identifier = ...
            'vi_wnl_user_run:FastModesBeforeCoefficients';
        wnlFailure.message = sprintf([ ...
            'WNL coefficient evaluation was skipped before nonlinear ', ...
            'forced solves because %s exceeds the configured slow-', ...
            'envelope limit %.3g.'], ...
            strjoin(failingModeMessages,'; '), ...
            input.weaklyNonlinear.maximumSlowRateRatio);
        wnlFailure.analysisAmplitude = p.aAnalysis;
        wnlFailure.criticalAmplitude = p.aCritical;
        wnlFailure.detuningFromCritical = p.aAnalysis-p.aCritical;
        wnlFailure.slowEnvelopeRatios = slowEnvelopeRatios;
        wnlFailure.maximumSlowRateRatio = ...
            input.weaklyNonlinear.maximumSlowRateRatio;
        wnlFailure.requiredAction = [ ...
            'Choose retained operating-point modes whose printed ', ...
            '|Re(lambda)|/omegaStar values are all below the slow-', ...
            'envelope limit, or move analysisAmplitude toward a point ', ...
            'where both selected branches are slow. For exploratory ', ...
            'coefficients with no quantitative WNL comparison, set ', ...
            'input.run.compareLinearAndWNL=false or set ', ...
            'input.weaklyNonlinear.requireSlowModesForComparison=false ', ...
            'and stopCoefficientRunWhenSlowEnvelopeFails=false.'];
        wnlResult = [];
        warning('vi_wnl_user_run:FastModesBeforeCoefficients', ...
            ['WNL COEFFICIENTS WERE NOT EVALUATED. %s Exact ', ...
             'linear results will still be plotted and saved.'], ...
            wnlFailure.message);
    else
    try
    % Start workers only when coefficient evaluation is about to use them.
    % Starting the pool before a multi-hour mode recovery lets its idle
    % timeout race the first nonlinear parfor loop.
    if ~input.run.modeRecoveryOnly && ...
            input.execution.useParallelNonlinearActions && ...
            input.execution.startParallelPool
        if license('test','Distrib_Computing_Toolbox')
            existingPool = gcp('nocreate');
            if isempty(existingPool)
                fprintf(['Starting nonlinear-action parallel pool ', ...
                    'immediately before coefficient evaluation.\n']);
                parpool('Processes',input.execution.parallelWorkers);
            end
        else
            warning('vi_wnl_user_run:NoParallelToolbox', ...
                ['Parallel nonlinear actions were requested, but the ', ...
                 'Parallel Computing Toolbox is unavailable.']);
        end
    end
    if input.run.modeRecoveryOnly
        recoveredModes = cell(numel(specs), 1);
        recoveredModeBars = cell(numel(specs), 1);
        recoveryReadiness = repmat(struct( ...
            'label','','linearReady',false,'coefficientReady',false, ...
            'referenceEigenvalueConsistent',true, ...
            'referenceEigenvalueAbsoluteMismatch',0, ...
            'referenceEigenvalueAllowedMismatch',Inf, ...
            'directResidual',NaN,'adjointResidual',NaN, ...
            'conjugateDirectResidual',NaN, ...
            'conjugateAdjointResidual',NaN),numel(specs),1);
        for recoveredModeIndex = 1:numel(specs)
            recoveredMode = wnl_compute_mode( ...
                model, specs{recoveredModeIndex}, opts);
            recoveredModeBar = wnl_conjugate_mode( ...
                model, recoveredMode, opts);
            fprintf(['Recovery-only direct residual %-12s', ...
                ' = %.6e\n'], recoveredMode.spec.label, ...
                recoveredMode.directResidual);
            fprintf(['Recovery-only adjoint residual %-11s', ...
                ' = %.6e\n'], recoveredMode.spec.label, ...
                recoveredMode.leftResidual);
            recoveredMode.residualReport = wnl_mode_residual_report( ...
                recoveredMode, operatorMetadata.layout);
            linearResidual = max([recoveredMode.directResidual, ...
                recoveredMode.leftResidual, ...
                recoveredModeBar.directResidual, ...
                recoveredModeBar.leftResidual]);
            coefficientResidual = max([recoveredMode.directResidual, ...
                recoveredMode.leftResidual, ...
                recoveredModeBar.directResidual]);
            referenceConsistency = ...
                wnl_reference_eigenvalue_consistency( ...
                recoveredMode,input.options);
            referenceAccepted = referenceConsistency.consistent || ...
                ~input.options.enforceReducedFullEigenvalueAgreement;
            recoveryReadiness(recoveredModeIndex).label = ...
                recoveredMode.spec.label;
            recoveryReadiness(recoveredModeIndex).linearReady = ...
                linearResidual <= input.options.modeResidualTolerance;
            recoveryReadiness(recoveredModeIndex).coefficientReady = ...
                recoveryReadiness(recoveredModeIndex).linearReady && ...
                coefficientResidual <= ...
                input.options.coefficientModeResidualTolerance && ...
                referenceAccepted;
            recoveryReadiness(recoveredModeIndex).referenceEigenvalueConsistent = ...
                referenceConsistency.consistent;
            recoveryReadiness(recoveredModeIndex).referenceEigenvalueAbsoluteMismatch = ...
                referenceConsistency.absoluteMismatch;
            recoveryReadiness(recoveredModeIndex).referenceEigenvalueAllowedMismatch = ...
                referenceConsistency.allowedMismatch;
            recoveryReadiness(recoveredModeIndex).directResidual = ...
                recoveredMode.directResidual;
            recoveryReadiness(recoveredModeIndex).adjointResidual = ...
                recoveredMode.leftResidual;
            recoveryReadiness(recoveredModeIndex).conjugateDirectResidual = ...
                recoveredModeBar.directResidual;
            recoveryReadiness(recoveredModeIndex).conjugateAdjointResidual = ...
                recoveredModeBar.leftResidual;
            fprintf(['Recovery readiness %-18s: linear=%d at %.1e, ', ...
                'coefficient=%d at %.1e; strict max residual %.3e\n'], ...
                recoveredMode.spec.label, ...
                recoveryReadiness(recoveredModeIndex).linearReady, ...
                input.options.modeResidualTolerance, ...
                recoveryReadiness(recoveredModeIndex).coefficientReady, ...
                input.options.coefficientModeResidualTolerance, ...
                coefficientResidual);
            if referenceConsistency.applicable
                fprintf(['  reduced/full exponent shift %.3e; ', ...
                    'allowed %.3e; consistent=%d\n'], ...
                    referenceConsistency.absoluteMismatch, ...
                    referenceConsistency.allowedMismatch, ...
                    referenceConsistency.consistent);
            end
            recoveredModes{recoveredModeIndex} = recoveredMode;
            recoveredModeBars{recoveredModeIndex} = recoveredModeBar;
        end
        wnlResult = struct();
        if numel(specs) == 1
            wnlResult.mode = recoveredModes{1};
            wnlResult.modeBar = recoveredModeBars{1};
            wnlResult.mu = NaN;
            wnlResult.g = NaN;
            wnlResult.validCubicScaling = false;
            wnlResult.linearCoefficient = ...
                wnl_spec_lambda(recoveredModes{1}.spec);
        else
            wnlResult.modes = recoveredModes;
            wnlResult.conjugateModes = recoveredModeBars;
            wnlResult.mu = complex(nan(numel(specs), 1));
            wnlResult.g = complex(nan(numel(specs)));
            wnlResult.validCubicScaling = ...
                false(numel(specs));
            wnlResult.linearCoefficients = cellfun(@(mode) ...
                wnl_spec_lambda(mode.spec), recoveredModes);
        end
        wnlResult.recoveryOnly = true;
        wnlResult.recoveryReadiness = recoveryReadiness;
        wnlResult.coefficientReady = all( ...
            [recoveryReadiness.coefficientReady]);
        if wnlResult.coefficientReady
            fprintf(['COEFFICIENT-READY RECOVERY: all %d retained ', ...
                'mode(s) passed the strict %.1e gate. Set ', ...
                'input.run.modeRecoveryOnly=false to evaluate WNL ', ...
                'coefficients on this same grid.\n'],numel(specs), ...
                input.options.coefficientModeResidualTolerance);
        elseif all([recoveryReadiness.linearReady])
            fprintf(['LINEAR-READY ONLY: the %.1e linear gate passed, ', ...
                'but at least one mode missed the %.1e coefficient ', ...
                'residual gate or the reduced/full exponent-agreement ', ...
                'gate. Keep modeRecoveryOnly=true, inspect the saved ', ...
                'residual report, and refine only the diagnosed temporal ', ...
                'or spatial direction.\n'], ...
                input.options.modeResidualTolerance, ...
                input.options.coefficientModeResidualTolerance);
        else
            fprintf(['RECOVERY INCOMPLETE: at least one retained mode ', ...
                'missed the %.1e linear residual gate. The finite mode ', ...
                'and its detailed lift/eigenpair diagnostics were saved ', ...
                'for inspection; nonlinear coefficients remain ', ...
                'disabled.\n'],input.options.modeResidualTolerance);
        end
    elseif numel(specs) == 1
        wnlResult = wnl_analyze_single_mode(model, specs{1}, opts);
        fprintf('Exact linear coefficient lambda = %.12g%+.12gi\n', ...
            real(wnlResult.linearCoefficient), ...
            imag(wnlResult.linearCoefficient));
        fprintf('Weakly nonlinear coefficient mu = %.12g%+.12gi\n', ...
            real(wnlResult.mu), imag(wnlResult.mu));
        fprintf('Weakly nonlinear coefficient g  = %.12g%+.12gi\n', ...
            real(wnlResult.g), imag(wnlResult.g));
        fprintf('Full-state direct residual      = %.6e\n', ...
            wnlResult.mode.directResidual);
        fprintf('Full-state left residual        = %.6e\n', ...
            wnlResult.mode.leftResidual);
        if isfield(wnlResult.mode, 'tracking') && ...
                isfield(wnlResult.mode.tracking, 'used') && ...
                wnlResult.mode.tracking.used
            fprintf('Constrained effective sigma    = %.6e\n', ...
                wnlResult.mode.directSingularValue);
            fprintf('Constrained scaled residual    = %.6e\n', ...
                wnlResult.mode.tracking.direct.scaledResidual);
            fprintf('Constrained LSQR flag/iters    = %d / %d\n', ...
                wnlResult.mode.tracking.direct.flag, ...
                wnlResult.mode.tracking.direct.iterations);
            fprintf('Selected lift attempt          = %d / %d\n', ...
                wnlResult.mode.tracking.direct.selectedAttempt, ...
                wnlResult.mode.tracking.direct.numberOfAttempts);
        end
        if max(wnlResult.mode.directResidual, ...
                wnlResult.mode.leftResidual) > ...
                input.options.linearRecoveryTolerance
            warning('vi_wnl_user_run:LinearRecoveryNotConverged', ...
                ['The full-state Floquet mode has not met the requested ', ...
                 'linear residual tolerance. Increase Nr/Nz/N and ', ...
                 'check that the full and reduced operating-point ', ...
                 'eigenpairs agree before using g.']);
        end
    else
        wnlResult = wnl_analyze_mode_set(model, specs, opts);
        disp('Exact operating-point linear coefficients lambda_j:');
        disp(wnlResult.linearCoefficients);
        disp('Detuning coefficients mu:');
        disp(wnlResult.mu);
        disp('Self/cross coefficient matrix g(j,k):');
        disp(wnlResult.g);
        if ~isempty(wnlResult.quadraticResonances)
            warning('vi_wnl_user_run:QuadraticResonance', ...
                ['Quadratic resonances were detected.  Inspect ', ...
                 'wnlResult.quadraticResonances before using a ', ...
                 'cubic-only Landau system.']);
        end
    end
    if ~isempty(wnlResult)
        % The reduced interface solve supplies the initial operating-point
        % exponent, but the full primitive-variable recovery may shift it.
        % Classify the slow-envelope regime using the exponent that actually
        % enters the returned amplitude equation, not the reduced seed.
        if useOperatingPointWnl
            if numel(specs) == 1 && ...
                    isfield(wnlResult,'linearCoefficient')
                recoveredLinearCoefficients = ...
                    wnlResult.linearCoefficient;
            elseif numel(specs) > 1 && ...
                    isfield(wnlResult,'linearCoefficients')
                recoveredLinearCoefficients = ...
                    wnlResult.linearCoefficients(:);
            else
                recoveredLinearCoefficients = [];
            end
            if numel(recoveredLinearCoefficients) == numel(specs) && ...
                    all(isfinite(real(recoveredLinearCoefficients))) && ...
                    all(isfinite(imag(recoveredLinearCoefficients)))
                slowEnvelopeRatios = abs(real( ...
                    recoveredLinearCoefficients(:))) / ...
                    max(p.omegaStar,eps);
                slowEnvelopeValid = all(slowEnvelopeRatios <= ...
                    input.weaklyNonlinear.maximumSlowRateRatio);
            end
        end
        wnlResult.referenceChoice = referenceChoice;
        wnlResult.slowEnvelopeRatios = slowEnvelopeRatios;
        wnlResult.slowEnvelopeValid = slowEnvelopeValid;
        wnlResult.maximumSlowRateRatio = ...
            input.weaklyNonlinear.maximumSlowRateRatio;
        if useOperatingPointWnl
            wnlResult.referenceAmplitude = p.aAnalysis;
            wnlResult.referenceType = ...
                'operating-point Floquet reduction';
            if numel(specs) == 1
                wnlResult.amplitudeEquation = ...
                    'dA/dt = lambda*A + g*abs(A)^2*A';
            else
                wnlResult.amplitudeEquation = ...
                    ['dA_j/dt = lambda_j*A_j + sum_k ', ...
                     'g(j,k)*A_j*abs(A_k)^2'];
            end
            wnlResult.reducedOperatingPointModes = ...
                operatingPointModes;
        else
            wnlResult.referenceAmplitude = p.aCritical;
            wnlResult.referenceType = ...
                'common-neutral-point reduction';
        end
        if isfield(wnlResult,'forcedSolvesValid') && ...
                isfield(wnlResult,'validCubicScaling')
            coefficientValuesFinite = isfield(wnlResult,'g') && ...
                all(isfinite(real(wnlResult.g(:)))) && ...
                all(isfinite(imag(wnlResult.g(:))));
            numericalCoefficientValidity = ...
                all(wnlResult.forcedSolvesValid(:)) && ...
                all(wnlResult.validCubicScaling(:)) && ...
                coefficientValuesFinite;
            if isfield(wnlResult,'quadraticResonances')
                noQuadraticResonance = ...
                    isempty(wnlResult.quadraticResonances);
            elseif isfield(wnlResult,'quadraticResonance')
                noQuadraticResonance = ...
                    ~logical(wnlResult.quadraticResonance);
            else
                noQuadraticResonance = false;
            end
            exploratoryCoefficientAvailability = ...
                isfield(wnlResult,'forcedSolvesExploratoryUsable') && ...
                all(wnlResult.forcedSolvesExploratoryUsable(:)) && ...
                coefficientValuesFinite && ...
                noQuadraticResonance;
            wnlResult.numericalCoefficientValidity = ...
                numericalCoefficientValidity;
            wnlResult.exploratoryCoefficientAvailability = ...
                exploratoryCoefficientAvailability;
            wnlResult.quantitativelyValid = ...
                numericalCoefficientValidity && slowEnvelopeValid;
            wnlResult.smallAmplitudeTransientAvailable = ...
                useOperatingPointWnl && numericalCoefficientValidity;
            wnlResult.smallAmplitudeTransientExploratoryAvailable = ...
                useOperatingPointWnl && ...
                (numericalCoefficientValidity || ...
                exploratoryCoefficientAvailability);
            fprintf(['WNL validity: forced/coefficient=%d, ', ...
                'exploratory-available=%d, slow-envelope=%d, ', ...
                'envelope-quantitative=%d, small-amplitude-transient=%d\n'], ...
                numericalCoefficientValidity, ...
                exploratoryCoefficientAvailability,slowEnvelopeValid, ...
                wnlResult.quantitativelyValid, ...
                wnlResult.smallAmplitudeTransientAvailable);
        end
    end
    catch wnlError
        recoverableModeFailure = startsWith(wnlError.identifier, ...
            'wnl_assert_mode_converged:') || ...
            startsWith(wnlError.identifier, ...
            'wnl_assert_reference_eigenvalue_consistent:') || ...
            startsWith(wnlError.identifier, ...
            'wnl_compute_mode:PhysicalModeLost') || ...
            startsWith(wnlError.identifier, ...
            'wnl_compute_mode:ZeroDescriptorPairingSeed');
        if ~recoverableModeFailure
            rethrow(wnlError);
        end
        wnlFailure.available = false;
        wnlFailure.status = 'Floquet mode recovery failed';
        wnlFailure.identifier = wnlError.identifier;
        wnlFailure.message = wnlError.message;
        wnlFailure.analysisAmplitude = p.aAnalysis;
        wnlFailure.criticalAmplitude = p.aCritical;
        wnlFailure.detuningFromCritical = ...
            p.aAnalysis-p.aCritical;
        wnlFailure.requiredAction = ...
            ['Use the exact linear result at the requested amplitude. ', ...
             'For WNL coefficients, keep recovery-only mode enabled. ', ...
             'If DAE algebraic completion cannot repair a pressure-', ...
             'inflated GMRES trial and the bordered correction equation ', ...
             'still misses its tolerance, do not add Newton steps: use ', ...
             'execution.profile=''final'' and refine N/Nr/the vertical ', ...
             'elements. Recheck the ', ...
             'direct/adjoint residuals and reduced/full eigenvalue ', ...
             'agreement without relaxing the acceptance gates.'];
        wnlResult = [];
        warning('vi_wnl_user_run:WnlModeRecoveryFailed', ...
            ['WNL COEFFICIENTS WERE NOT EVALUATED. %s The complete ', ...
             'linear result will still be plotted and saved.'], ...
            wnlError.message);
    end
    end

    if input.run.plotHarmonicNorms && ~isempty(wnlResult)
        if numel(specs) == 1
            fieldsToPlot = {wnlResult.mode.field};
        else
            fieldsToPlot = cellfun(@(x) x.field, wnlResult.modes, ...
                'UniformOutput', false);
        end
        figure('Name', 'Direct Floquet harmonic norms');
        tiledlayout(numel(fieldsToPlot), 1);
        for j = 1:numel(fieldsToPlot)
            nexttile;
            field = fieldsToPlot{j};
            harmonicNorm = sqrt(sum(abs(field.coeff).^2, 1));
            stem(field.spec.n+field.spec.s, harmonicNorm, 'filled');
            grid on;
            xlabel('n+s');
            ylabel('||q_n||_2');
            title(field.spec.label, 'Interpreter', 'none');
        end
    end
end

%% Compare the linear transient with the weakly nonlinear Landau model
comparisonResult = struct();
comparisonResult.requested = logical(input.run.compareLinearAndWNL);
comparisonResult.available = false;
comparisonResult.status = 'not requested';
comparisonResult.skipReason = '';
comparisonResult.requiredAction = '';
comparisonResult.exploratory = false;
comparisonResult.quantitativelyValid = false;
comparisonResult.forcedSolvesValid = false;
comparisonResult.forcedSolvesExploratoryUsable = false;
comparisonResult.transientModel = transientModel;
if input.run.compareLinearAndWNL
    if isfield(wnlFailure, 'status')
        comparisonResult.status = 'skipped';
        comparisonResult.skipReason = wnlFailure.message;
        comparisonResult.requiredAction = ...
            wnlFailure.requiredAction;
        if isfield(linearResult, 'growthRateStar')
            comparisonResult.linearGrowthRate = ...
                linearResult.growthRateStar;
            comparisonResult.analysisAmplitude = ...
                linearResult.aAnalysis;
        end
        fprintf('\nLINEAR RESULT AVAILABLE; WNL COMPARISON NOT COMPUTED\n');
        fprintf('  reason: %s\n', comparisonResult.skipReason);
        fprintf('  action: %s\n', comparisonResult.requiredAction);
    elseif input.run.modeRecoveryOnly
        comparisonResult.status = 'skipped';
        comparisonResult.skipReason = ...
            ['input.run.modeRecoveryOnly is true, so the WNL ', ...
             'coefficients mu and g were not evaluated.'];
        comparisonResult.requiredAction = ...
            ['After both recovery residuals pass, set ', ...
             'input.run.modeRecoveryOnly=false and rerun the script.'];
        if isfield(linearResult, 'growthRateStar')
            comparisonResult.linearGrowthRate = ...
                linearResult.growthRateStar;
        end
        fprintf('\nLINEAR/WNL COMPARISON NOT COMPUTED\n');
        fprintf('  reason: %s\n', comparisonResult.skipReason);
        fprintf('  action: %s\n', comparisonResult.requiredAction);
    elseif ~input.run.weaklyNonlinear || isempty(wnlResult)
        comparisonResult.status = 'skipped';
        comparisonResult.skipReason = ...
            ['input.run.weaklyNonlinear is false or the WNL ', ...
             'calculation did not return a result.'];
        comparisonResult.requiredAction = ...
            'Set input.run.weaklyNonlinear=true and rerun the script.';
        fprintf('\nLINEAR/WNL COMPARISON NOT COMPUTED\n');
        fprintf('  reason: %s\n', comparisonResult.skipReason);
        fprintf('  action: %s\n', comparisonResult.requiredAction);
    elseif ~isfield(linearResult, 'growthRateStar')
        comparisonResult.status = 'skipped';
        comparisonResult.skipReason = ...
            'The linear Floquet calculation did not return a growth rate.';
        comparisonResult.requiredAction = ...
            'Set input.run.linearPreview=true and inspect the linear solve.';
        warning('vi_wnl_user_run:NoLinearResultForComparison', ...
            'A linear Floquet result is required for the comparison.');
    else
        if numel(input.modes) == 1
            muVector = wnlResult.mu;
            gMatrix = wnlResult.g;
            validCubicScaling = wnlResult.validCubicScaling;
            exactLinearCoefficientVector = ...
                wnlResult.linearCoefficient;
            hasQuadraticResonance = wnlResult.quadraticResonance;
            forcedSolvesValid = wnlResult.forcedSolvesValid;
            if isfield(wnlResult,'forcedSolvesExploratoryUsable')
                forcedSolvesExploratoryUsable = ...
                    wnlResult.forcedSolvesExploratoryUsable;
            else
                forcedSolvesExploratoryUsable = forcedSolvesValid;
            end
        else
            muVector = wnlResult.mu(:);
            gMatrix = wnlResult.g;
            validCubicScaling = all(wnlResult.validCubicScaling(:));
            exactLinearCoefficientVector = ...
                wnlResult.linearCoefficients(:);
            hasQuadraticResonance = ...
                ~isempty(wnlResult.quadraticResonances);
            forcedSolvesValid = all(wnlResult.forcedSolvesValid(:));
            if isfield(wnlResult,'forcedSolvesExploratoryUsable')
                forcedSolvesExploratoryUsable = all( ...
                    wnlResult.forcedSolvesExploratoryUsable(:));
            else
                forcedSolvesExploratoryUsable = forcedSolvesValid;
            end
        end
        muTarget = muVector(1);
        gTarget = gMatrix(1, 1);
        slowEnvelopeComparisonValid = true;
        if isfield(wnlResult,'slowEnvelopeValid')
            slowEnvelopeComparisonValid = ...
                logical(wnlResult.slowEnvelopeValid);
        end

        if useOperatingPointWnl
            linearCoefficientsFinite = all(isfinite(real( ...
                exactLinearCoefficientVector(:)))) && all(isfinite(imag( ...
                exactLinearCoefficientVector(:))));
        else
            linearCoefficientsFinite = all(isfinite(real(muVector(:)))) && ...
                all(isfinite(imag(muVector(:))));
        end
        coefficientsFinite = linearCoefficientsFinite && ...
            all(isfinite(real(gMatrix(:)))) && ...
            all(isfinite(imag(gMatrix(:))));
        exploratoryForcedTrajectory = ...
            input.weaklyNonlinear. ...
            allowExploratoryTrajectoryWithUnconvergedForcedFields && ...
            ~forcedSolvesValid && forcedSolvesExploratoryUsable && ...
            ~hasQuadraticResonance;
        comparisonIsExploratory = exploratoryForcedTrajectory || ...
            (~useSmallAmplitudeTransient && ...
            ~slowEnvelopeComparisonValid);
        if input.weaklyNonlinear.requireSlowModesForComparison && ...
                ~slowEnvelopeComparisonValid && ...
                ~useSmallAmplitudeTransient
            comparisonResult.status = 'unavailable';
            comparisonResult.skipReason = sprintf([ ...
                'At least one retained mode has |Re(lambda)|/omegaStar ', ...
                'above the configured slow-envelope limit %.3g.'], ...
                input.weaklyNonlinear.maximumSlowRateRatio);
            comparisonResult.requiredAction = [ ...
                'Choose two slow modes at this acceleration or move the ', ...
                'analysis amplitude toward a point where both growth ', ...
                'rates are small. The computed operating-point cubic ', ...
                'coefficients may be retained as exploratory diagnostics ', ...
                'but are not labeled a quantitative WNL transient.'];
            warning('vi_wnl_user_run:FastModesInvalidateWnlComparison', ...
                ['The requested two-mode reduction is outside the ', ...
                 'configured slow-envelope regime. Exact linear results ', ...
                 'remain valid, but the WNL transient was withheld.']);
        elseif ~forcedSolvesValid && ...
                ~exploratoryForcedTrajectory
            comparisonResult.status = 'unavailable';
            comparisonResult.skipReason = ...
                ['One or more O(A^2) forced fields failed the ', ...
                 'forcing-relative residual gate.'];
            comparisonResult.requiredAction = ...
                ['Inspect each forced field''s DAE-completion/state-norm ', ...
                 'diagnostics. Increase forced iterations only when that ', ...
                 'solve has not reached its correction floor; otherwise ', ...
                 'refine N/Nr/the vertical elements and nonlinear ', ...
                 'projection. An exploratory trajectory is available only ', ...
                 'when every field is below ', ...
                 'forcedExploratoryResidualTolerance.'];
            warning('vi_wnl_user_run:UnconvergedForcedFields', ...
                ['At least one slaved field missed both the strict and ', ...
                 'exploratory residual gates, so no WNL trajectory was ', ...
                 'formed. This is not a quadratic resonance.']);
        elseif hasQuadraticResonance || ...
                (~validCubicScaling && ~exploratoryForcedTrajectory)
            comparisonResult.status = 'unavailable';
            comparisonResult.skipReason = ...
                ['A quadratic resonance makes the cubic-only Landau ', ...
                 'comparison invalid.'];
            comparisonResult.requiredAction = ...
                'Derive and integrate the resonant amplitude system.';
            warning('vi_wnl_user_run:InvalidCubicComparison', ...
                ['The first retained mode has a quadratic resonance. ', ...
                 'A cubic Landau transient is not valid.']);
        elseif ~coefficientsFinite
            comparisonResult.status = 'unavailable';
            comparisonResult.skipReason = ...
                'One or more WNL coefficients are not finite.';
            comparisonResult.requiredAction = ...
                'Inspect operators.P, C, D and the coefficient solves.';
            warning('vi_wnl_user_run:MissingWnlCoefficients', ...
                ['The WNL coefficients are not finite. Check that ', ...
                 'operators.P, C, and D are implemented.']);
        else
            comparisonResult.available = true;
            comparisonResult.exploratory = comparisonIsExploratory;
            comparisonResult.quantitativelyValid = ...
                ~comparisonIsExploratory;
            comparisonResult.forcedSolvesValid = forcedSolvesValid;
            comparisonResult.forcedSolvesExploratoryUsable = ...
                forcedSolvesExploratoryUsable;
            if comparisonIsExploratory
                comparisonResult.status = ...
                    'computed exploratory (not quantitatively validated)';
            elseif useSmallAmplitudeTransient
                comparisonResult.status = ...
                    'computed small-amplitude cubic correction';
            else
                comparisonResult.status = 'computed';
            end
            if exploratoryForcedTrajectory
                warning( ...
                    'vi_wnl_user_run:ExploratoryForcedFieldTrajectory', ...
                    ['Computing the requested trajectory from finite ', ...
                     'forced fields below %.3e that did not all pass the ', ...
                     'strict %.3e residual gate. Coefficients and ', ...
                     'trajectory are exploratory, not converged.'], ...
                    input.options.forcedExploratoryResidualTolerance, ...
                    input.options.forcedSolveResidualTolerance);
            end
            amplitudeScale = ...
                input.comparison.zetaOverHPerUnitAmplitude;
            scaleSource = 'input.comparison';
            if isfield(operatorMetadata, ...
                    'zetaOverHPerUnitAmplitude')
                amplitudeScale = ...
                    operatorMetadata.zetaOverHPerUnitAmplitude;
                scaleSource = 'operatorMetadata';
            else
                warning('vi_wnl_user_run:AssumedAmplitudeNormalization', ...
                    ['Using input.comparison.', ...
                     'zetaOverHPerUnitAmplitude=%.6g. ', ...
                     'The growth-rate comparison is normalization ', ...
                     'independent, but the nonlinear saturation ', ...
                     'amplitude is not.'], amplitudeScale);
            end
            validateattributes(amplitudeScale, {'numeric'}, ...
