%% VI_WNL_USER_RUN_FULL_CYLINDER  Editable full-cylinder WNL input
%
% This version calculates all dimensionless groups from physical inputs,
% searches for the dominant linear Floquet root, reconstructs the interface
% motion, compares exact linear growth with the WNL Landau model, and
% outputs/plots the signed differences (linear minus WNL).
%
% Change values only in the "USER INPUTS" section first.  This file can:
%   1. convert dimensional inputs to the dimensionless parameters used by
%      the original Vibrated-Interface linear solver;
%   2. compute the legacy H or SH neutral acceleration for diagnostics;
%   3. obtain one or two exact Floquet modes at any requested acceleration;
%   4. run the full weakly nonlinear coefficient engine using the included
%      primitive-variable cylinder operator factory B0/Lhat/C/D/P.
%
% Run from the repository root with
%   run(['weakly_nonlinear/examples/', ...
%       'vi_wnl_user_run_full_cylinder.m'])
%
% The WNL calculation uses cylinder_wnl_operators.m. It retains primitive
% velocity and pressure variables, incompressibility, the fixed-domain ALE
% residual, the linear solver's wall/interface conditions, and the selected
% free or pinned contact-line row. The radial derivatives may be enriched by
% the known Bessel branches, while the vertical direction may use one global
% Chebyshev grid or several matched elements. Always check convergence in N,
% Nr, the vertical element sizes, Ntheta, and the directional-
% differentiation steps before using g.

